//! Peer and client configuration for developer localnets.
//!
//! Peer files carry node essentials only: identity and transport keys, the trusted roster,
//! the signed genesis, listener addresses, one private state root per peer, and a few
//! developer settings (batched fsync, loopback rate-limit bypass, operator-signed diagnostics,
//! fast transaction gossip for one-second blocks). Every other value is the node default.
//! The storage layer adds its provider owners and provider HTTPS listeners.

use super::*;
use iroha_config::{base::toml::TomlSource, parameters::actual};
use iroha_crypto::{Hash, HashOf};
use iroha_data_model::block::BlockHeader;
use toml::{Table, Value};

/// Header of every operator-visible generated peer configuration.
pub(super) const PEER_CONFIG_HEADER: &str = "\
# Generated by `kagami localnet generate`; start the network with ./start.sh.
#
# A node of this network needs its identity and bindings (chain, public_key and its keys,
# trusted_peers, trusted_peers_pop, [network], [torii], [genesis]). The other values pin
# localnet-tuned limits and this peer's state paths; a hand-written node omits them
# (`kagami node init` writes such a file).

";
/// Root of every per-peer state directory, beside `storage/peerN` (Kura).
const STATE_DIRECTORY: &str = "state";
/// Root of every per-peer Kura store.
const STORAGE_DIRECTORY: &str = "storage";
/// Managed node data directories, completed by the node-config loader.
const MANAGED_NODES_DIRECTORY: &str = "nodes";
/// Relative path of the bundled rANS table the streaming codec loads at startup.
pub(super) const RANS_TABLE_RELATIVE_PATH: &str = "codec/rans/tables/rans_seed0.toml";
/// Nexus storage budget; the node refuses to start on a nearly full disk without one.
pub(super) const NEXUS_STORAGE_BUDGET_BYTES: i64 = 1024 * 1024 * 1024;
/// Queue capacity for developer workloads.
const QUEUE_CAPACITY: i64 = 20_000;
/// Smaller queue for throughput presets, which measure finality rather than backlog.
const PERF_QUEUE_CAPACITY: i64 = 4_096;
/// Queue time to live.
const QUEUE_TTL_MS: i64 = 600_000;
/// Loopback sources that bypass Torii pre-authorization and API rate limits.
const LOOPBACK_CIDRS: [&str; 2] = ["127.0.0.0/8", "::1/128"];
/// Transaction gossip cadence for one-second (or faster) blocks.
const FAST_TX_GOSSIP_MS: i64 = 100;
/// Logger filter for throughput presets, which would otherwise log every transaction.
const PERF_LOGGER_FILTER: &str = "info,iroha_torii::routing=warn";
/// Ed25519 signature batch size for throughput presets.
const PERF_SIGNATURE_BATCH_MAX_ED25519: i64 = 64;
/// Admission puzzle for all-loopback validators: cheap enough for fast local handshakes.
const LOOPBACK_PUZZLE_DIFFICULTY: i64 = 6;
const LOOPBACK_PUZZLE_MEMORY_KIB: i64 = 4_096;
/// Client transaction time to live and status wait.
const CLIENT_TTL_MS: u64 = 600_000;
const CLIENT_STATUS_TIMEOUT_MS: u64 = 300_000;

/// Paths of one peer's private state under a render root.
struct PeerPaths {
    kura: PathBuf,
    state: PathBuf,
    data_dir: Option<PathBuf>,
}

impl PeerPaths {
    fn new(root: &Path, index: usize, managed: bool) -> Self {
        Self {
            kura: root.join(STORAGE_DIRECTORY).join(format!("peer{index}")),
            state: root.join(STATE_DIRECTORY).join(format!("peer{index}")),
            data_dir: managed.then(|| {
                root.join(MANAGED_NODES_DIRECTORY)
                    .join(format!("peer{index}"))
            }),
        }
    }

    fn state(&self, relative: &str) -> Value {
        path_value(&self.state.join(relative))
    }
}

/// SoraFS storage root of one peer, where storage providers keep their attestation custody.
pub(super) fn sorafs_storage_dir(root: &Path, index: usize) -> PathBuf {
    PeerPaths::new(root, index, false).state.join("sorafs")
}

/// How a rendered configuration names the signed genesis identity.
#[derive(Clone, Copy)]
enum GenesisIdentity {
    /// Placeholder hash used only to parse the bootstrap configuration before signing.
    BootstrapInline,
    /// The published `genesis.expected_hash` file beside the configuration.
    PublishedFile,
}

/// Everything shared by the peer configurations of one generation.
pub(super) struct Layout<'a> {
    pub(super) request: &'a Request<'a>,
    pub(super) peers: &'a [Peer],
    pub(super) genesis_public_key: &'a PublicKey,
    pub(super) operator_public_key: &'a PublicKey,
    pub(super) authorities: Option<&'a service_authorities::GeneratedAuthorities>,
}

impl Layout<'_> {
    /// Create every peer's private state directories in the staging directory.
    pub(super) fn prepare_directories(&self, out_dir: &Path) -> Result<()> {
        for index in 0..self.peers.len() {
            let paths = PeerPaths::new(out_dir, index, self.request.managed());
            for directory in [&paths.kura, &paths.state]
                .into_iter()
                .chain(paths.data_dir.as_ref())
            {
                custody::ensure_directory(directory).wrap_err_with(|| {
                    format!("failed to create peer directory {}", directory.display())
                })?;
            }
        }
        Ok(())
    }

    /// Parse peer 0's configuration, rendered in the staging directory, to derive the
    /// execution, Nexus and DA policies that signed genesis commits.
    pub(super) fn parse_bootstrap(&self, out_dir: &Path) -> Result<actual::Root> {
        let rendered = self.render(0, out_dir, GenesisIdentity::BootstrapInline)?;
        parse_peer_config(&rendered, &out_dir.join("peer0.toml"))
    }

    /// Write every peer configuration for the publication root after checking, in the
    /// staging directory, that the node loader accepts it and that it names the signed genesis.
    /// Returns the configurations parsed in the staging directory.
    pub(super) fn write_peer_configs(
        &self,
        out_dir: &Path,
        genesis_hash: HashOf<BlockHeader>,
    ) -> Result<Vec<actual::Root>> {
        let render_root = self.request.render_root(out_dir);
        let mut parsed_configs = Vec::with_capacity(self.peers.len());
        for index in 0..self.peers.len() {
            let path = out_dir.join(format!("peer{index}.toml"));
            let rendered = self.render(index, out_dir, GenesisIdentity::PublishedFile)?;
            let parsed = parse_peer_config(&rendered, &path).wrap_err_with(|| {
                format!("generated validator config peer{index}.toml failed node validation")
            })?;
            ensure!(
                parsed.genesis.expected_hash == genesis_hash,
                "generated validator config peer{index}.toml names genesis {}, expected {genesis_hash}",
                parsed.genesis.expected_hash
            );
            let published = if render_root == out_dir {
                rendered
            } else {
                self.render(index, render_root, GenesisIdentity::PublishedFile)?
            };
            let published = if self.request.managed() {
                published
            } else {
                Zeroizing::new(format!("{PEER_CONFIG_HEADER}{}", published.as_str()))
            };
            write_owner_only(&path, published.as_bytes())?;
            parsed_configs.push(parsed);
        }
        Ok(parsed_configs)
    }

    /// Render peer `index` for `root`, with the storage layer's additions when present.
    fn render(
        &self,
        index: usize,
        root: &Path,
        identity: GenesisIdentity,
    ) -> Result<Zeroizing<String>> {
        let rendered = self.render_node(index, root, identity);
        match self.authorities {
            Some(authorities) => {
                authorities.configure_peer(&rendered, self.request.chain_discriminant, root, index)
            }
            None => Ok(rendered),
        }
    }

    #[allow(clippy::too_many_lines)]
    fn render_node(
        &self,
        index: usize,
        root: &Path,
        identity: GenesisIdentity,
    ) -> Zeroizing<String> {
        let request = self.request;
        let opts = request.opts;
        let peer = &self.peers[index];
        let paths = PeerPaths::new(root, index, request.managed());
        let mut config = crate::secret_toml::Table::new(Table::new());
        config.insert("chain".into(), Value::String(request.chain_id.clone()));
        if let Some(discriminant) = request.chain_discriminant {
            config.insert(
                "chain_discriminant".into(),
                Value::Integer(i64::from(discriminant)),
            );
        }
        if let Some(data_dir) = &paths.data_dir {
            config.insert("data_dir".into(), path_value(data_dir));
        }
        config.insert(
            "public_key".into(),
            Value::String(peer.public_key.to_string()),
        );
        config.insert(
            "private_key".into(),
            Value::String(peer.private_key.to_string()),
        );
        config.insert(
            "soranet_transport_private_key".into(),
            Value::String(peer.transport_private_key.to_string()),
        );
        config.insert(
            "soranet_transport_public_key".into(),
            Value::String(peer.transport_public_key.to_string()),
        );
        config.insert(
            "trusted_peers".into(),
            Value::Array(
                self.peers
                    .iter()
                    .map(|peer| {
                        Value::String(format!(
                            "{}@{}",
                            peer.public_key,
                            request.public_host.addr_literal(peer.p2p_port)
                        ))
                    })
                    .collect(),
            ),
        );
        config.insert(
            "trusted_peers_pop".into(),
            Value::Array(
                self.peers
                    .iter()
                    .map(|peer| {
                        Value::Table(Table::from_iter([
                            (
                                "public_key".to_owned(),
                                Value::String(peer.public_key.to_string()),
                            ),
                            ("pop_hex".to_owned(), Value::String(hex::encode(&peer.pop))),
                        ]))
                    })
                    .collect(),
            ),
        );
        config.insert("telemetry_profile".into(), Value::String("extended".into()));

        let mut genesis = Table::new();
        genesis.insert("file".into(), path_value(&root.join("genesis.signed.nrt")));
        genesis.insert(
            "public_key".into(),
            Value::String(self.genesis_public_key.to_string()),
        );
        match identity {
            GenesisIdentity::BootstrapInline => {
                let placeholder = HashOf::<BlockHeader>::from_untyped_unchecked(Hash::new(
                    b"Kagami localnet policy-derivation placeholder",
                ));
                genesis.insert(
                    "expected_hash".into(),
                    Value::String(NetworkId::from_genesis_hash(placeholder).to_string()),
                );
            }
            GenesisIdentity::PublishedFile => {
                genesis.insert(
                    "expected_hash_file".into(),
                    Value::String(GENESIS_EXPECTED_HASH_FILE.to_owned()),
                );
            }
        }
        config.insert("genesis".into(), Value::Table(genesis));

        config.insert(
            "kura".into(),
            Value::Table(Table::from_iter([
                ("store_dir".to_owned(), path_value(&paths.kura)),
                ("fsync_mode".to_owned(), Value::String("batched".into())),
            ])),
        );
        if paths.data_dir.is_none() {
            config.insert(
                "snapshot".into(),
                Value::Table(Table::from_iter([(
                    "store_dir".to_owned(),
                    paths.state("snapshot"),
                )])),
            );
        }
        let logger_filter = opts.perf_profile.map(|_| PERF_LOGGER_FILTER);
        let mut logger = Table::from_iter([
            ("format".to_owned(), Value::String("compact".into())),
            ("level".to_owned(), Value::String("info".into())),
        ]);
        if let Some(filter) = logger_filter {
            logger.insert("filter".into(), Value::String(filter.into()));
        }
        config.insert("logger".into(), Value::Table(logger));

        config.insert("network".into(), Value::Table(self.network(peer, &paths)));
        config.insert(
            "nexus".into(),
            Value::Table(Table::from_iter([(
                "storage".to_owned(),
                Value::Table(Table::from_iter([(
                    "local_budget_bytes".to_owned(),
                    Value::Integer(NEXUS_STORAGE_BUDGET_BYTES),
                )])),
            )])),
        );
        let queue_capacity = if opts.perf_profile.is_some() {
            PERF_QUEUE_CAPACITY
        } else {
            QUEUE_CAPACITY
        };
        config.insert(
            "queue".into(),
            Value::Table(Table::from_iter([
                ("capacity".to_owned(), Value::Integer(queue_capacity)),
                (
                    "capacity_per_user".to_owned(),
                    Value::Integer(queue_capacity),
                ),
                (
                    "transaction_time_to_live_ms".to_owned(),
                    Value::Integer(QUEUE_TTL_MS),
                ),
            ])),
        );
        if opts.perf_profile.is_some() {
            config.insert(
                "pipeline".into(),
                Value::Table(Table::from_iter([(
                    "signature_batch_max_ed25519".to_owned(),
                    Value::Integer(PERF_SIGNATURE_BATCH_MAX_ED25519),
                )])),
            );
        }

        // Safety records and the key installation log live beside the peer's state, outside
        // Kura: `start.sh` asserts fresh keys exactly when the records directory is absent.
        config.insert(
            "sumeragi".into(),
            Value::Table(Table::from_iter([
                ("role".to_owned(), Value::String("validator".into())),
                ("records_dir".to_owned(), paths.state("sumeragi-records")),
                (
                    "installation_log".to_owned(),
                    paths.state("sumeragi-installation.log"),
                ),
            ])),
        );
        config.insert(
            "streaming".into(),
            Value::Table(Table::from_iter([
                (
                    "identity_public_key".to_owned(),
                    Value::String(peer.streaming_public_key.to_string()),
                ),
                (
                    "identity_private_key".to_owned(),
                    Value::String(peer.streaming_private_key.to_string()),
                ),
                ("session_store_dir".to_owned(), paths.state("streaming")),
                ("codec".to_owned(), Value::Table(codec_table(root))),
            ])),
        );
        // These subsystems keep state even when idle; every peer owns a disjoint root.
        config.insert(
            "soracloud_runtime".into(),
            Value::Table(Table::from_iter([(
                "state_dir".to_owned(),
                paths.state("soracloud_runtime"),
            )])),
        );
        config.insert(
            "sorafs".into(),
            Value::Table(Table::from_iter([
                (
                    "storage".to_owned(),
                    Value::Table(Table::from_iter([(
                        "data_dir".to_owned(),
                        paths.state("sorafs"),
                    )])),
                ),
                (
                    "por".to_owned(),
                    Value::Table(Table::from_iter([(
                        "state_dir".to_owned(),
                        paths.state("sorafs/por"),
                    )])),
                ),
            ])),
        );
        config.insert(
            "tiered_state".into(),
            Value::Table(Table::from_iter([
                ("cold_store_root".to_owned(), paths.state("tiered_state")),
                ("da_store_root".to_owned(), paths.state("da_wsv_snapshots")),
            ])),
        );
        config.insert(
            "torii".into(),
            Value::Table(self.torii(peer, &paths, queue_capacity)),
        );
        // Governance accounts keep their code defaults: omitted account settings stay valid for
        // every chain prefix, so the generated config does not restate them.
        let rendered = toml::to_string(&*config).expect("generated peer config must encode");
        Zeroizing::new(rendered)
    }

    fn network(&self, peer: &Peer, paths: &PeerPaths) -> Table {
        let request = self.request;
        let mut network = Table::from_iter([
            (
                "address".to_owned(),
                Value::String(request.bind_host.addr_literal(peer.p2p_port)),
            ),
            (
                "public_address".to_owned(),
                Value::String(request.public_host.addr_literal(peer.p2p_port)),
            ),
        ]);
        if request.block_cadence_ms <= DEFAULT_BLOCK_CADENCE_MS {
            for key in [
                "transaction_gossip_period_ms",
                "transaction_gossip_public_target_reshuffle_ms",
                "transaction_gossip_restricted_target_reshuffle_ms",
            ] {
                network.insert(key.into(), Value::Integer(FAST_TX_GOSSIP_MS));
            }
            network.insert("transaction_gossip_resend_ticks".into(), Value::Integer(1));
        }
        let mut pow = Table::from_iter([(
            "revocation_store_path".to_owned(),
            paths.state("soranet/ticket_revocations.norito"),
        )]);
        if self.all_loopback() {
            pow.insert(
                "difficulty".into(),
                Value::Integer(LOOPBACK_PUZZLE_DIFFICULTY),
            );
            pow.insert(
                "puzzle".into(),
                Value::Table(Table::from_iter([
                    (
                        "memory_kib".to_owned(),
                        Value::Integer(LOOPBACK_PUZZLE_MEMORY_KIB),
                    ),
                    ("time_cost".to_owned(), Value::Integer(1)),
                    ("lanes".to_owned(), Value::Integer(1)),
                ])),
            );
        }
        network.insert(
            "soranet_handshake".into(),
            Value::Table(Table::from_iter([("pow".to_owned(), Value::Table(pow))])),
        );
        if let Some(discriminant) = request.chain_discriminant {
            // The disabled VPN profile still parses its default operator (the governance bond
            // escrow) as an account literal, which must use the chain's address prefix.
            network.insert(
                "soranet_vpn".into(),
                Value::Table(Table::from_iter([(
                    "operator_account_id".to_owned(),
                    Value::String(account_literal(
                        &iroha_config::parameters::defaults::governance::bond_escrow_account_id(),
                        discriminant,
                    )),
                )])),
            );
        }
        network
    }

    fn torii(&self, peer: &Peer, paths: &PeerPaths, queue_capacity: i64) -> Table {
        let loopback = || {
            Value::Array(
                LOOPBACK_CIDRS
                    .iter()
                    .map(|cidr| Value::String((*cidr).to_owned()))
                    .collect(),
            )
        };
        let mut torii = Table::from_iter([
            (
                "address".to_owned(),
                Value::String(self.request.bind_host.addr_literal(peer.api_port)),
            ),
            ("data_dir".to_owned(), paths.state("torii")),
            (
                "da_ingest".to_owned(),
                Value::Table(Table::from_iter([
                    (
                        "replay_cache_store_dir".to_owned(),
                        paths.state("torii/da_replay"),
                    ),
                    (
                        "manifest_store_dir".to_owned(),
                        paths.state("torii/da_manifests"),
                    ),
                ])),
            ),
            ("preauth_allow_cidrs".to_owned(), loopback()),
            ("api_rate_limit_bypass_cidrs".to_owned(), loopback()),
            (
                "api_high_load_tx_threshold".to_owned(),
                Value::Integer(queue_capacity),
            ),
            // Generated bundles ship no prover-key directory.
            ("zk_prover_enabled".to_owned(), Value::Boolean(false)),
            // Operator-only diagnostics (peers, time, pipeline) accept the runtime operator key.
            (
                "operator_signatures".to_owned(),
                Value::Table(Table::from_iter([
                    ("enabled".to_owned(), Value::Boolean(true)),
                    (
                        "allowed_public_keys".to_owned(),
                        Value::Array(vec![Value::String(self.operator_public_key.to_string())]),
                    ),
                ])),
            ),
        ]);
        if self.request.managed() {
            // Mochi drives managed networks through the MCP tool surface.
            torii.insert(
                "mcp".into(),
                Value::Table(Table::from_iter([
                    ("enabled".to_owned(), Value::Boolean(true)),
                    ("profile".to_owned(), Value::String("writer".into())),
                    ("expose_operator_routes".to_owned(), Value::Boolean(false)),
                    (
                        "allow_tool_prefixes".to_owned(),
                        Value::Array(vec![Value::String("iroha.".into())]),
                    ),
                ])),
            );
        }
        torii
    }

    /// Whether every listener, advertisement and trusted peer is a numeric loopback address.
    fn all_loopback(&self) -> bool {
        let loopback = |host: &CanonicalHost| {
            host.url_host()
                .trim_start_matches('[')
                .trim_end_matches(']')
                .parse::<std::net::IpAddr>()
                .is_ok_and(|ip| ip.is_loopback())
        };
        loopback(&self.request.bind_host) && loopback(&self.request.public_host)
    }
}

/// The streaming codec defaults with the bundled rANS table. The node reads `streaming.codec`
/// as one value, so naming the table path means naming every field.
fn codec_table(root: &Path) -> Table {
    use iroha_config::parameters::defaults::streaming::codec;
    Table::from_iter([
        (
            "cabac_mode".to_owned(),
            Value::String(codec::CABAC_MODE.to_owned()),
        ),
        (
            "trellis_blocks".to_owned(),
            Value::Array(
                codec::trellis_blocks()
                    .into_iter()
                    .map(|size| Value::Integer(i64::from(size)))
                    .collect(),
            ),
        ),
        (
            "rans_tables_path".to_owned(),
            path_value(&root.join(RANS_TABLE_RELATIVE_PATH)),
        ),
        (
            "entropy_mode".to_owned(),
            Value::String(codec::entropy_mode()),
        ),
        (
            "bundle_width".to_owned(),
            Value::Integer(i64::from(codec::bundle_width())),
        ),
        (
            "bundle_accel".to_owned(),
            Value::String(codec::bundle_accel()),
        ),
    ])
}

/// Parse a rendered peer configuration exactly as `iroha3d --config` loads it.
///
/// A configuration with `data_dir` goes through the node-config loader, which completes the
/// derived state and secret paths; a flat configuration is parsed directly.
pub(super) fn parse_peer_config(rendered: &str, path: &Path) -> Result<actual::Root> {
    let table = crate::secret_toml::parse_table(rendered, "generated localnet peer config")?;
    let _chain_discriminant = table
        .get("chain_discriminant")
        .and_then(Value::as_integer)
        .and_then(|value| u16::try_from(value).ok())
        .map(ChainDiscriminantGuard::enter);
    if table.contains_key("data_dir") {
        use iroha_config::node_config::{NodeConfigOptions, NodeFile, open_node_config};
        let node = open_node_config(
            NodeFile::Verified {
                path: path.to_path_buf(),
                table,
            },
            NodeConfigOptions::default(),
        )
        .map_err(|error| invalid(path, "has an invalid data_dir layout", &error))?;
        let (user, _) = node
            .read()
            .map_err(|error| invalid(path, "is invalid", &error))?;
        return user
            .parse()
            .map_err(|error| invalid(path, "fails validation", &error));
    }
    actual::Root::from_toml_source(TomlSource::new_sensitive(
        path.to_path_buf(),
        table,
        crate::secret_toml::zeroize_table,
    ))
    .map_err(|error| invalid(path, "is invalid", &error))
}

/// Name only typed schema categories: report attachments may carry private values.
fn invalid<C: ?Sized>(
    path: &Path,
    problem: &str,
    error: &error_stack::Report<C>,
) -> color_eyre::eyre::Report {
    eyre!(
        "generated localnet peer config {} {problem}: {}",
        path.display(),
        crate::sora_network::generated_config_error_categories(error)
    )
}

/// Write `client.toml` for the generated client signer, with the storage layer's
/// `[musubi.publication]` client when present.
pub(super) fn write_client_config(
    out_dir: &Path,
    request: &Request<'_>,
    client: &Identity,
    transport: HttpTransportPolicy,
    publication: Option<&Table>,
) -> Result<()> {
    let rendered = render_client_config(
        request.opts.base_api_port,
        &request.public_host,
        &request.chain_id,
        request.chain_discriminant,
        client,
        transport,
        publication,
    )?;
    write_owner_only(&out_dir.join("client.toml"), rendered.as_bytes())
}

/// Render `client.toml`. The storage layer re-renders it to authenticate a retained generation
/// byte for byte.
pub(super) fn render_client_config(
    base_api_port: u16,
    public_host: &CanonicalHost,
    chain: &str,
    chain_discriminant: Option<u16>,
    client: &Identity,
    transport: HttpTransportPolicy,
    publication: Option<&Table>,
) -> Result<Zeroizing<String>> {
    let discriminant = chain_discriminant
        .unwrap_or_else(iroha_config::parameters::defaults::common::chain_discriminant);
    // Render explicitly so long keys are not re-wrapped by a pretty printer.
    let rendered = Zeroizing::new(format!(
        concat!(
            "chain = \"{chain}\"\n",
            "network_id_file = \"{network_id_file}\"\n",
            "torii_url = \"{torii_url}\"\n",
            "http_transport_policy = \"{transport}\"\n",
            "\n",
            "[transaction]\n",
            "time_to_live_ms = {ttl_ms}\n",
            "status_timeout_ms = {status_timeout_ms}\n",
            "nonce = false\n",
            "\n",
            "[account]\n",
            "chain_discriminant = {discriminant}\n",
            "private_key = \"{private_key}\"\n",
            "public_key = \"{public_key}\"\n",
        ),
        chain = chain,
        network_id_file = GENESIS_EXPECTED_HASH_FILE,
        torii_url = public_host.torii_url(base_api_port),
        transport = transport.as_str(),
        ttl_ms = CLIENT_TTL_MS,
        status_timeout_ms = CLIENT_STATUS_TIMEOUT_MS,
        discriminant = discriminant,
        private_key = client.private_key.as_str(),
        public_key = client.public_key,
    ));
    let mut rendered = rendered;
    if let Some(publication) = publication {
        let musubi =
            Table::from_iter([("publication".to_owned(), Value::Table(publication.clone()))]);
        rendered.push('\n');
        rendered.push_str(
            &toml::to_string(&Table::from_iter([(
                "musubi".to_owned(),
                Value::Table(musubi),
            )]))
            .wrap_err("encode generated publication client")?,
        );
    }
    Ok(rendered)
}

pub(super) fn account_literal(account: &AccountId, discriminant: u16) -> String {
    account
        .to_i105_for_discriminant(discriminant)
        .expect("known account must render for the requested chain discriminant")
}

fn path_value(path: &Path) -> Value {
    Value::String(path.to_string_lossy().into_owned())
}
