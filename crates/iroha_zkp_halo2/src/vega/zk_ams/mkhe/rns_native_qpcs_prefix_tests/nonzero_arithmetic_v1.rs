//! Independent nonzero arithmetic known answers for both qPCS polynomial roles.
//!
//! Reproduce with `python3 scripts/zk_ams_prefix_nonzero_vectors_v1.py`.
//! Python uses arbitrary-precision integer arithmetic and conjugate/norm
//! inversion, independently of the Rust field implementation. These vectors
//! exercise local equations; they are not transcript-bound proof fixtures.

use super::*;

#[test]
fn independent_nonzero_polynomials_quotients_batches_and_folds_cover_all_40_fields() {
    let fields = derive_fields_v1().expect("canonical forty extension fields");
    for (limb, (field, expected)) in fields.into_iter().zip(VECTORS).enumerate() {
        let pair = |offset| Fq2V1 {
            c0: expected[offset],
            c1: expected[offset + 1],
        };
        assert_eq!(field.modulus, expected[0], "modulus at limb {limb}");
        assert_eq!(field.nonresidue, expected[1], "nonresidue at limb {limb}");
        assert_eq!(field.domain_root, pair(2), "LDE root at limb {limb}");
        let x = field.pow(field.domain_root, (17 + 2 * limb) as u128);
        assert_eq!(x, pair(4), "LDE coordinate at limb {limb}");
        let a = Fq2V1::base(17 + limb as u64);
        assert_eq!(a.c0, expected[6]);
        // F(T)=(T^N+1)G(T), with G a nonconstant cubic in every limb.
        let coefficients = [
            5 + limb as u64,
            7 + 2 * limb as u64,
            11 + 3 * limb as u64,
            13 + 5 * limb as u64,
        ];
        let g = |t| {
            coefficients
                .iter()
                .rev()
                .fold(Fq2V1::ZERO, |value, &coefficient| {
                    field.add(field.mul(value, t), Fq2V1::base(coefficient))
                })
        };
        let f = |t| {
            field.mul(
                field.add(
                    field.pow(t, ZK_AMS_MKHE_RELEASE_RING_DEGREE_V1 as u128),
                    Fq2V1::ONE,
                ),
                g(t),
            )
        };
        let evaluations = [f(a), g(a)];
        assert_eq!(
            evaluations,
            [Fq2V1::base(expected[7]), Fq2V1::base(expected[8])]
        );
        let points = [x, field.sub(Fq2V1::ZERO, x)];
        let values = [f(points[0]), f(points[1]), g(points[0]), g(points[1])];
        let mut quotients = [Fq2V1::ZERO; 4];
        let mut batches = [Fq2V1::ZERO; 4];
        let batch_a = Fq2V1 {
            c0: field.modulus - 17,
            c1: 23,
        };
        let batch_b = Fq2V1 {
            c0: 29,
            c1: field.modulus - 31,
        };
        let alpha = Fq2V1 {
            c0: 37,
            c1: field.modulus - 41,
        };
        for index in 0..4 {
            assert_eq!(
                values[index],
                pair(9 + 2 * index),
                "polynomial {index}, limb {limb}"
            );
            let denominator = field.sub(points[index % 2], a);
            quotients[index] = field.mul(
                field.sub(values[index], evaluations[index / 2]),
                field
                    .inverse(denominator)
                    .expect("nonzero opening denominator"),
            );
            assert_eq!(
                quotients[index],
                pair(17 + 2 * index),
                "quotient {index}, limb {limb}"
            );
            assert_ne!(values[index], Fq2V1::ZERO);
            assert_ne!(quotients[index], Fq2V1::ZERO);
            batches[index] = batch_value_v1(
                field,
                points[index % 2],
                values[index],
                quotients[index],
                batch_a,
                batch_b,
                index / 2,
            );
            assert_eq!(
                batches[index],
                pair(25 + 2 * index),
                "batch {index}, limb {limb}"
            );
            assert_ne!(batches[index], Fq2V1::ZERO);
            // Every one of the five repetitions uses the same even/odd degree lift.
            for repetition in 0..REPETITIONS_V1 {
                assert_eq!(
                    batch_value_v1(
                        field,
                        points[index % 2],
                        values[index],
                        quotients[index],
                        batch_a,
                        batch_b,
                        2 * repetition + index / 2
                    ),
                    pair(25 + 2 * index),
                );
            }
        }
        for role in 0..2 {
            let positive = batches[2 * role];
            let negative = batches[2 * role + 1];
            let expected_fold = pair(33 + 2 * role);
            assert_ne!(expected_fold, Fq2V1::ZERO);
            assert_eq!(
                fold_value_v1(field, x, positive, negative, alpha).unwrap(),
                expected_fold
            );
            assert_eq!(
                fold_value_with_inverse_x_v1(
                    field,
                    field.inverse(x).unwrap(),
                    positive,
                    negative,
                    alpha
                ),
                expected_fold,
            );
            assert_ne!(
                fold_value_v1(field, x, negative, positive, alpha).unwrap(),
                expected_fold
            );
            assert_ne!(
                fold_value_v1(field, x, positive, negative, field.add(alpha, Fq2V1::ONE)).unwrap(),
                expected_fold,
            );
        }
    }
}

