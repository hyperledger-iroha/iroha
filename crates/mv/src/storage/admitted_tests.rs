fn replacement_fixture(
    budget: &AllocationBudget,
) -> (Storage<u64, u64, Prepaid<Policy>>, Arc<Records>) {
    let records = Arc::new(Records {
        live: Mutex::new(Vec::new()),
        panic_on: AtomicUsize::new(usize::MAX),
    });
    let provider = |reservation| Policy {
        reservation,
        records: Arc::clone(&records),
        component: 0,
    };
    let storage = Storage::try_new_with_node_custody(budget, provider).unwrap();
    budget.with_deferred_refund_notifications(|| {
        let mut block = storage.try_block_admitted(budget, provider).unwrap();
        let mut tx = block.try_transaction().unwrap();
        for (key, value) in [(1, 10), (2, 20), (4, 40)] {
            tx.try_insert_admitted(key, value, budget, provider)
                .unwrap();
        }
        tx.apply();
        block.commit();
        let mut block = storage.try_block_admitted(budget, provider).unwrap();
        let mut tx = block.try_transaction().unwrap();
        assert_eq!(
            tx.try_remove_admitted(&1, budget, provider).unwrap(),
            Some(10)
        );
        tx.try_insert_admitted(2, 21, budget, provider).unwrap();
        tx.try_insert_admitted(3, 30, budget, provider).unwrap();
        tx.apply();
        block.commit();
    });
    (storage, records)
}

#[test]
fn admitted_replacement_retains_mode_and_restored_preimages_through_detachment() {
    let budget = AllocationBudget::new(1 << 20);
    let (storage, records) = replacement_fixture(&budget);
    let provider = |reservation| Policy {
        reservation,
        records: Arc::clone(&records),
        component: 0,
    };
    let current = storage.blocks.read();
    let undo = storage.revert.read();
    let predecessor = storage.publication.capture();
    budget.with_deferred_refund_notifications(|| {
        let mut block = storage
            .try_block_and_revert_admitted(&budget, provider)
            .unwrap();
        assert_eq!(block.mode(), BlockMode::Replace);
        assert!(block.is_dirty());
        assert_eq!(
            block.iter().map(|(k, v)| (*k, *v)).collect::<Vec<_>>(),
            [(1, 10), (2, 20), (4, 40)]
        );
        assert!(block.revert_map().is_empty());
        let mut tx = block.try_transaction().unwrap();
        tx.try_insert_admitted(2, 22, &budget, provider).unwrap();
        tx.try_insert_admitted(3, 33, &budget, provider).unwrap();
        tx.apply();
        assert_eq!(block.get_before_block(&2), Some(&20));
        assert_eq!(block.get_before_block(&3), None);
        let detached = block.try_detach(|_| Ok::<_, ()>(())).unwrap();
        assert_eq!(detached.mode(), BlockMode::Replace);
        let prepared = detached
            .try_prepare_publication(&storage, |_, _| Ok::<_, ()>(()))
            .unwrap_or_else(|_| panic!("same original roots"));
        let detached = prepared.abort();
        assert_eq!(
            predecessor.try_check_current::<()>(&storage.publication),
            Ok(())
        );
        assert_eq!(current.get(&2), Some(&21));
        assert_eq!(undo.get(&2), Some(&Some(20)));
        let prepared = detached
            .try_prepare_publication(&storage, |_, _| Ok::<_, ()>(()))
            .unwrap_or_else(|_| panic!("abort retains exact original successors"));
        prepared.publish();
        assert_eq!(
            storage
                .blocks
                .read()
                .iter()
                .map(|(k, v)| (*k, *v))
                .collect::<Vec<_>>(),
            [(1, 10), (2, 22), (3, 33), (4, 40)]
        );
        assert_eq!(
            storage
                .revert
                .read()
                .iter()
                .map(|(k, v)| (*k, *v))
                .collect::<Vec<_>>(),
            [(2, Some(20)), (3, None)]
        );
        // Replacing the replacement starts from its own predecessor, not from
        // the discarded block or a preimage generated by the rollback itself.
        let next = storage
            .try_block_and_revert_admitted(&budget, provider)
            .unwrap();
        assert_eq!(
            next.iter().map(|(k, v)| (*k, *v)).collect::<Vec<_>>(),
            [(1, 10), (2, 20), (4, 40)]
        );
        drop(next);
    });
    assert_eq!(current.get(&2), Some(&21));
    assert_eq!(undo.get(&1), Some(&Some(10)));
    drop(current);
    drop(undo);
    drop(storage);
    assert_eq!(budget.reserved_bytes(), 0);
}

#[test]
fn admitted_replacement_contention_names_only_the_original_held_writer() {
    for hold_undo in [false, true] {
        let budget = AllocationBudget::new(1 << 20);
        let (storage, records) = replacement_fixture(&budget);
        let provider = |reservation| Policy {
            reservation,
            records: Arc::clone(&records),
            component: 0,
        };
        budget.with_deferred_refund_notifications(|| {
            // Different value types prevent one guard variable; retain each
            // original owner in its own optional slot instead.
            let undo = hold_undo.then(|| storage.try_block_admitted(&budget, provider).unwrap());
            let current = (!hold_undo).then(|| {
                storage.blocks_released.poisoning_guard(
                    storage
                        .blocks
                        .try_write_admitted(|demand| {
                            Ok::<_, ()>(provider(budget.try_reserve_bytes(demand.bytes()).unwrap()))
                        })
                        .unwrap(),
                )
            });
            let expected = if hold_undo {
                storage.revert_released.observe()
            } else {
                storage.blocks_released.observe()
            };
            let predecessor = storage.publication.capture();
            let before = budget.reserved_bytes();
            let error = storage
                .try_block_and_revert_admitted(&budget, |_| {
                    panic!("held writer refuses before allocation")
                })
                .err()
                .unwrap();
            let admitted::StorageAdmissionError::Busy(wait) = error else {
                panic!("expected original release dependency");
            };
            assert_eq!(wait, expected);
            assert_eq!(budget.reserved_bytes(), before);
            assert_eq!(
                predecessor.try_check_current::<()>(&storage.publication),
                Ok(())
            );
            let mut future = std::pin::pin!(wait.wait_for_release());
            assert!(
                future
                    .as_mut()
                    .poll(&mut Context::from_waker(Waker::noop()))
                    .is_pending()
            );
            drop(undo);
            drop(current);
            assert!(
                future
                    .as_mut()
                    .poll(&mut Context::from_waker(Waker::noop()))
                    .is_ready()
            );
            let block = storage
                .try_block_and_revert_admitted(&budget, provider)
                .unwrap();
            assert_eq!(block.get(&1), Some(&10));
            assert_eq!(block.get(&2), Some(&20));
            assert!(block.get(&3).is_none());
            drop(block);
        });
        drop(storage);
        assert_eq!(budget.reserved_bytes(), 0);
    }
}

