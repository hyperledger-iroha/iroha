#[test]
fn admitted_replacement_final_undo_clear_refusal_preserves_original_pair() {
    let budget = AllocationBudget::new(1 << 20);
    let (storage, records) = replacement_fixture(&budget);
    let provider = |reservation| Policy {
        reservation,
        records: Arc::clone(&records),
        component: 0,
    };
    budget.with_deferred_refund_notifications(|| {
        // The unchanged block leaves an empty undo tree. Replacement still
        // needs a newly admitted empty root before its owner can escape.
        storage
            .try_block_admitted(&budget, provider)
            .unwrap()
            .commit();
        let predecessor = storage.publication.capture();
        let before = budget.reserved_bytes();
        let mut held = None;
        let mut calls = 0;
        let error = storage
            .try_block_and_revert_admitted(&budget, |reservation| {
                calls += 1;
                if calls == 2 {
                    held = Some(
                        budget
                            .try_reserve_bytes(budget.limit_bytes() - budget.reserved_bytes())
                            .unwrap(),
                    );
                }
                provider(reservation)
            })
            .err()
            .unwrap();
        assert!(matches!(
            error,
            admitted::StorageAdmissionError::Capacity(_)
        ));
        assert_eq!(
            calls, 2,
            "the final clear refuses after both original shells"
        );
        assert_eq!(
            predecessor.try_check_current::<()>(&storage.publication),
            Ok(())
        );
        assert_eq!(storage.blocks.read().get(&2), Some(&21));
        assert!(storage.revert.read().is_empty());
        drop(held);
        assert_eq!(budget.reserved_bytes(), before);
        storage
            .try_block_and_revert_admitted(&budget, provider)
            .unwrap()
            .commit();
    });
    drop(storage);
    assert_eq!(budget.reserved_bytes(), 0);
}

#[test]
fn admitted_replacement_factory_cleanup_cannot_return_a_partial_owner() {
    struct FactoryCleanup;
    impl FactoryCleanup {
        fn retain(&self) {}
    }
    impl Drop for FactoryCleanup {
        fn drop(&mut self) {
            panic!("injected factory cleanup failure");
        }
    }
    let budget = AllocationBudget::new(1 << 20);
    let (storage, records) = replacement_fixture(&budget);
    let provider = |reservation| Policy {
        reservation,
        records: Arc::clone(&records),
        component: 0,
    };
    let before = budget.reserved_bytes();
    let predecessor = storage.publication.capture();
    budget.with_deferred_refund_notifications(|| {
        let bomb = FactoryCleanup;
        let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            let _ = storage.try_block_and_revert_admitted(&budget, move |reservation| {
                bomb.retain();
                provider(reservation)
            });
        }));
        assert!(result.is_err());
        assert_eq!(budget.reserved_bytes(), before);
        assert_eq!(
            predecessor.try_check_current::<()>(&storage.publication),
            Ok(())
        );
        assert_eq!(storage.blocks.read().get(&2), Some(&21));
        assert_eq!(storage.revert.read().get(&2), Some(&Some(20)));
        assert!(storage.revert_released.observe().is_poisoned());
        assert!(storage.blocks_released.observe().is_poisoned());
        let error = storage
            .try_block_and_revert_admitted(&budget, |_| {
                panic!("poison refuses before policy construction")
            })
            .err()
            .unwrap();
        assert!(matches!(error, admitted::StorageAdmissionError::Poisoned));
    });
    drop(storage);
    assert_eq!(budget.reserved_bytes(), 0);
}

struct Records {
    live: Mutex<Vec<(usize, bool, usize)>>,
    panic_on: AtomicUsize,
}
struct Charge {
    credit: AllocationCharge,
    id: usize,
    records: Arc<Records>,
}
impl Drop for Charge {
    fn drop(&mut self) {
        self.records.live.lock().unwrap()[self.id].1 = false;
        assert!(
            self.records
                .panic_on
                .compare_exchange(self.id, usize::MAX, SeqCst, SeqCst)
                .is_err(),
            "injected first current-map retirement panic"
        );
        // Original credit stays owned until the containing charge drops.
        let _ = self.credit.layout();
    }
}
struct Policy {
    reservation: AllocationReservation,
    records: Arc<Records>,
    component: usize,
}
impl NodeFunding for Policy {
    type Charge = Charge;
    fn take_node_charge(&mut self, layout: Layout) -> Charge {
        let mut records = self.records.live.lock().unwrap();
        let id = records.len();
        records.push((layout.size(), true, self.component));
        Charge {
            credit: self.reservation.try_split(layout).unwrap(),
            id,
            records: Arc::clone(&self.records),
        }
    }
}
impl NodeCloning<u64, u64> for Policy {
    fn clone_key(&mut self, key: &u64) -> u64 {
        *key
    }
    fn clone_value(&mut self, value: &u64) -> u64 {
        REPLACEMENT_REPLAN.with(|mode| match mode.get() {
            1 => mode.set(2),
            3 => mode.set(4),
            _ => {}
        });
        *value
    }
}
impl ClonePlanning<u64, u64> for Policy {
    fn plan_key(_: &u64, demand: &mut AllocationDemand) -> Result<(), PlanningError> {
        match REPLACEMENT_REPLAN.with(|mode| mode.get()) {
            2 => Err(PlanningError::UnsupportedPayload),
            4 => demand.add_layout(Layout::new::<u64>()),
            _ => Ok(()),
        }
    }
    fn plan_value(value: &u64, _: &mut AllocationDemand) -> Result<(), PlanningError> {
        if REFUSED_REPLACEMENT_VALUE.with(|refused| refused.get()) == Some(*value) {
            Err(PlanningError::UnsupportedPayload)
        } else {
            Ok(())
        }
    }
}

thread_local! {
    static REFUSED_REPLACEMENT_VALUE: std::cell::Cell<Option<u64>> = const { std::cell::Cell::new(None) };
    static REPLACEMENT_REPLAN: std::cell::Cell<u8> = const { std::cell::Cell::new(0) };
}

#[test]
fn admitted_replacement_second_plan_refusal_returns_a_healthy_original_pair() {
    for mode in [1, 3] {
        let budget = AllocationBudget::new(1 << 20);
        let (storage, records) = replacement_fixture(&budget);
        let provider = |reservation| Policy {
            reservation,
            records: Arc::clone(&records),
            component: 0,
        };
        let before = budget.reserved_bytes();
        let predecessor = storage.publication.capture();
        budget.with_deferred_refund_notifications(|| {
            // The first plan succeeds; incoming value cloning changes only the
            // test policy. The second plan must return its typed refusal.
            REPLACEMENT_REPLAN.with(|state| state.set(mode));
            let error = storage
                .try_block_and_revert_admitted(&budget, provider)
                .err()
                .unwrap();
            REPLACEMENT_REPLAN.with(|state| state.set(0));
            match (mode, error) {
                (
                    1,
                    admitted::StorageAdmissionError::Planning(PlanningError::UnsupportedPayload),
                )
                | (3, admitted::StorageAdmissionError::Changed) => {}
                (_, error) => panic!("replanning lost its original refusal: {error:?}"),
            }
            assert_eq!(budget.reserved_bytes(), before);
            assert_eq!(
                predecessor.try_check_current::<()>(&storage.publication),
                Ok(())
            );
            assert_eq!(storage.blocks.read().get(&2), Some(&21));
            assert_eq!(storage.revert.read().get(&2), Some(&Some(20)));
            let retry = storage
                .try_block_and_revert_admitted(&budget, provider)
                .unwrap();
            assert_eq!(retry.get(&1), Some(&10));
            assert_eq!(retry.get(&2), Some(&20));
            assert!(retry.get(&3).is_none());
            drop(retry);
        });
        drop(storage);
        assert_eq!(budget.reserved_bytes(), 0);
    }
}

