    fn edge_scalars<F: BigPrimeField>() -> Vec<F> {
        let modulus: BigUint = modulus::<F>();
        let half: BigUint = &modulus >> 1;
        let zero = &modulus - &modulus;
        let one = &zero + 1_u8;
        vec![
            zero,
            one,
            &half - 1_u8,
            half,
            (&modulus + 1_u8) >> 1,
            &modulus - 2_u8,
            &modulus - 1_u8,
        ]
        .into_iter()
        .map(|value| biguint_to_fe::<F>(&value))
        .collect()
    }

