fn digest_u16_le(values: &[u16]) -> Vec<u8> {
    let mut encoded = Vec::with_capacity(2 * values.len());
    for value in values {
        encoded.extend_from_slice(&value.to_le_bytes());
    }
    Sha256::digest(encoded).to_vec()
}

