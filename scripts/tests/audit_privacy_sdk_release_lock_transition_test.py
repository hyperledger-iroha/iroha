#!/usr/bin/env python3
"""Focused adversarial tests for the privacy release lock transition audit."""

from __future__ import annotations

import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[2]
AUDITOR_PATH = ROOT / "ci/audit_privacy_sdk_release_lock_transition.py"
V1_PATH = ROOT / "ci/privacy_sdk_release_lock_v1.toml"
V2_PATH = ROOT / "ci/privacy_sdk_release_lock_v2.toml"

SPEC = importlib.util.spec_from_file_location("privacy_lock_transition_auditor", AUDITOR_PATH)
if SPEC is None or SPEC.loader is None:
    raise RuntimeError(f"unable to load {AUDITOR_PATH}")
AUDITOR = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = AUDITOR
SPEC.loader.exec_module(AUDITOR)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def copy_authority(source: Path, destination: Path) -> Path:
    shutil.copyfile(source, destination)
    destination.chmod(0o644)
    return destination


class PrivacyReleaseLockTransitionAuditTest(unittest.TestCase):
    maxDiff = None

    def run_auditor(self, *arguments: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(AUDITOR_PATH), *arguments],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            env={"PATH": os.environ.get("PATH", "")},
        )

    def test_committed_transition_is_admissible_and_deterministic(self) -> None:
        first = self.run_auditor("--json")
        second = self.run_auditor("--json")
        self.assertEqual(first.returncode, 0, first.stderr)
        self.assertEqual(second.returncode, 0, second.stderr)
        self.assertEqual(first.stdout, second.stdout)

        evidence = json.loads(first.stdout)
        self.assertEqual(evidence["schema"], AUDITOR.SCHEMA)
        self.assertEqual(evidence["status"], "admissible")
        self.assertEqual(evidence["v1"]["sha256"], AUDITOR.V1_SHA256)
        self.assertEqual(evidence["v2"]["sha256"], AUDITOR.V2_SHA256)
        self.assertEqual(evidence["v1"]["path"], "ci/privacy_sdk_release_lock_v1.toml")
        self.assertEqual(evidence["v2"]["path"], "ci/privacy_sdk_release_lock_v2.toml")
        self.assertEqual(evidence["v1"]["mode"], "0644")
        self.assertEqual(evidence["v2"]["mode"], "0644")
        self.assertEqual(evidence["transition"]["dependency_change_count"], 45)
        self.assertEqual(
            evidence["transition"]["dependency_delta_sha256"],
            AUDITOR.DEPENDENCY_DELTA_SHA256,
        )
        self.assertEqual(evidence["workspace"]["local_package_count"], 101)
        self.assertEqual(
            evidence["workspace"]["manifest_dependency_projection_sha256"],
            AUDITOR.LOCAL_MANIFEST_DEPENDENCY_PROJECTION_SHA256,
        )

    def test_default_human_summary_is_concise(self) -> None:
        result = self.run_auditor()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("transition is admissible", result.stdout)
        self.assertIn("packages 1213 -> 1188", result.stdout)
        self.assertIn("dependency changes 45", result.stdout)

    def test_v1_byte_mutation_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            mutated = copy_authority(V1_PATH, Path(temporary) / "Cargo.lock")
            raw = mutated.read_bytes()
            mutated.write_bytes(raw.replace(b'name = "ab_glyph"', b'name = "ab_glypf"', 1))
            mutated.chmod(0o644)
            result = self.run_auditor("--v1-lock", str(mutated))
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("SHA-256 mismatch", result.stderr)

    def test_v2_truncation_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            truncated = copy_authority(V2_PATH, Path(temporary) / "Cargo.lock")
            truncated.write_bytes(truncated.read_bytes()[:4096])
            truncated.chmod(0o644)
            result = self.run_auditor("--v2-lock", str(truncated))
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("SHA-256 mismatch", result.stderr)

    def test_noncanonical_content_is_rejected_even_with_matching_test_digest(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            malformed = copy_authority(V2_PATH, Path(temporary) / "Cargo.lock")
            raw = malformed.read_bytes().replace(
                b"# This file is automatically @generated by Cargo.\n",
                b"# non-canonical generated lock header.............\n",
                1,
            )
            malformed.write_bytes(raw)
            malformed.chmod(0o644)
            with self.assertRaisesRegex(AUDITOR.AuditError, "canonical Cargo lock v4 header"):
                AUDITOR.load_lock_authority(
                    malformed, "malformed test lock", hashlib.sha256(raw).hexdigest()
                )

    def test_mode_drift_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            private = copy_authority(V2_PATH, Path(temporary) / "Cargo.lock")
            private.chmod(0o600)
            result = self.run_auditor("--v2-lock", str(private))
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("mode must be exactly 0644", result.stderr)

    def test_symlink_replacement_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            replacement = Path(temporary) / "Cargo.lock"
            replacement.symlink_to(V2_PATH)
            result = self.run_auditor("--v2-lock", str(replacement))
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("must be a regular file", result.stderr)

    def test_hardlink_replacement_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            original = copy_authority(V2_PATH, Path(temporary) / "authority")
            replacement = Path(temporary) / "Cargo.lock"
            os.link(original, replacement)
            result = self.run_auditor("--v2-lock", str(replacement))
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("must be singly linked", result.stderr)

    def test_dependency_delta_mutation_fails_complete_transition_proof(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            mutated = copy_authority(V2_PATH, Path(temporary) / "Cargo.lock")
            raw = mutated.read_bytes()
            start = raw.index(b'name = "iroha_js_host"')
            end = raw.index(b"[[package]]", start)
            record = raw[start:end]
            self.assertIn(b' "iroha_torii_shared",\n', record)
            record = record.replace(
                b' "iroha_torii_shared",\n', b' "iroha_test_samples",\n', 1
            )
            raw = raw[:start] + record + raw[end:]
            mutated.write_bytes(raw)
            mutated.chmod(0o644)

            v1 = AUDITOR.load_lock_authority(V1_PATH, "test v1", AUDITOR.V1_SHA256)
            v2 = AUDITOR.load_lock_authority(mutated, "mutated v2", hashlib.sha256(raw).hexdigest())
            with self.assertRaisesRegex(
                AUDITOR.AuditError,
                "dependency-list transition",
            ):
                AUDITOR.audit_transition(v1, v2)

    def test_local_manifest_dependency_drift_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            fixture = Path(temporary)
            for source in ROOT.rglob("Cargo.toml"):
                if "target" in source.parts or ".git" in source.parts:
                    continue
                relative = source.relative_to(ROOT)
                destination = fixture / relative
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, destination)
            copy_authority(ROOT / "Cargo.lock", fixture / "Cargo.lock")

            manifest = fixture / "crates/iroha_js_host/Cargo.toml"
            text = manifest.read_text(encoding="utf-8")
            dependency = 'iroha_torii_shared = { workspace = true }\n'
            self.assertIn(dependency, text)
            manifest.write_text(
                text.replace(dependency, "", 1),
                encoding="utf-8",
                newline="\n",
            )

            v2 = AUDITOR.load_lock_authority(V2_PATH, "test v2", AUDITOR.V2_SHA256)
            with self.assertRaisesRegex(
                AUDITOR.AuditError, "local manifest dependency projection changed"
            ):
                AUDITOR.audit_workspace(fixture, v2)

    def test_authority_modes_and_hashes_are_exact(self) -> None:
        for path, expected in ((V1_PATH, AUDITOR.V1_SHA256), (V2_PATH, AUDITOR.V2_SHA256)):
            with self.subTest(path=path.name):
                metadata = path.lstat()
                self.assertTrue(stat.S_ISREG(metadata.st_mode))
                self.assertEqual(metadata.st_nlink, 1)
                self.assertEqual(stat.S_IMODE(metadata.st_mode), 0o644)
                self.assertEqual(sha256(path), expected)


if __name__ == "__main__":
    unittest.main()
