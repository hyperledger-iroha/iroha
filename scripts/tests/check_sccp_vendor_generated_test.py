def hash1(files: dict[str, bytes]) -> str:
    rows = [hashlib.sha256(data).hexdigest() + "  " + name + "\n" for name, data in sorted(files.items())]
    digest = hashlib.sha256("".join(rows).encode()).digest()
    return "h1:" + base64.b64encode(digest).decode()


def make_zip(files, *, compression=zipfile.ZIP_DEFLATED) -> bytes:
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", compression=compression) as archive:
        for name, data in files:
            archive.writestr(name, data)
    return stream.getvalue()


class Fixture:
    def __init__(self, root: Path):
        self.root = root
        self.files = {
            "go.mod": f"module {MODULE}\n\ngo 1.20\n".encode(),
            "pkg/generated.go": HEADER + b"package pkg\nconst Value = 7\n",
            "internal/generator.go": b"package main\nfunc main() {}\n",
        }
        self.write("circuits/sccp/go.mod", f"module example.com/local\n\ngo 1.20\n\nrequire (\n {MODULE} {VERSION} // indirect\n)\n")
        self.write("circuits/sccp/vendor/modules.txt", f"# {MODULE} {VERSION}\n## explicit; go 1.20\n{MODULE}/pkg\n")
        self.write(OUTPUT, self.files["pkg/generated.go"])
        self.manifest()
        self.pin()

    def write(self, relative: str, data: str | bytes):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data.encode() if isinstance(data, str) else data)

    def manifest(self, outputs=None):
        self.write("generated-files.toml", f'''schema_version = 1

[policy]
forbidden_tracked_globs = ["target/**"]
allowed_tracked_paths = []
generated_source_extensions = [".go"]

[[generated]]
name = "sccp-vendor-example"
kind = "file"
external = true
outputs = {json.dumps([OUTPUT] if outputs is None else outputs)}
generator = "upstream generator imported by go mod vendor"
generator_sources = []
inputs = ["circuits/sccp/go.mod", "circuits/sccp/go.sum", "circuits/sccp/vendor/modules.txt"]
check = "python3 scripts/check_sccp_vendor_generated.py"
provenance = "Existing module and go.mod checksums authenticate the upstream generated bytes."
''')

    def pin(self):
        self.archive_sum = hash1({PREFIX + name: data for name, data in self.files.items()})
        self.mod_sum = hash1({"go.mod": self.files["go.mod"]})
        self.write("circuits/sccp/go.sum", f"{MODULE} {VERSION} {self.archive_sum}\n{MODULE} {VERSION}/go.mod {self.mod_sum}\n")

    def blob(self):
        return make_zip((PREFIX + name, data) for name, data in self.files.items())

    def run(self, loader=None):
        return check.verify(self.root, archive_loader=loader or (lambda module, version: self.blob()))

    def authenticate(self, blob=None, outputs=None, archive_sum=None, mod_sum=None):
        return check.authenticated_outputs(
            self.blob() if blob is None else blob, MODULE, VERSION,
            archive_sum or self.archive_sum, mod_sum or self.mod_sum,
            {"pkg/generated.go"} if outputs is None else outputs,
        )


