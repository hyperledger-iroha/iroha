@pytest.mark.parametrize("change", ["duplicate", "case-collision", "wrong-prefix", "symlink", "fifo", "compression", "nul"])
def test_ambiguous_archive_entries_fail(fixture, change):
    entries = [(PREFIX + key, value) for key, value in fixture.files.items()]
    name = PREFIX + "pkg/extra.go"
    if change == "duplicate":
        entries.append(entries[-1])
    elif change == "case-collision":
        entries.append((PREFIX + "pkg/Generated.go", b"bad"))
    elif change == "wrong-prefix":
        entries.append(("example.com/other@v1.2.3/pkg/a.go", b"bad"))
    elif change in ("symlink", "fifo"):
        info = zipfile.ZipInfo(name)
        info.create_system = 3
        info.external_attr = ((stat.S_IFLNK if change == "symlink" else stat.S_IFIFO) | 0o644) << 16
        entries.append((info, b"target"))
    elif change == "compression":
        info = zipfile.ZipInfo(name)
        info.compress_type = zipfile.ZIP_BZIP2
        entries.append((info, b"bad"))
    else:
        blob = make_zip(entries + [(name, b"bad")])
        blob = blob.replace(b"extra.go", b"extra\x00go")
        with pytest.raises(check.VerificationError):
            fixture.authenticate(blob)
        return
    if change == "duplicate":
        with pytest.warns(UserWarning, match="Duplicate name"):
            blob = make_zip(entries)
    else:
        blob = make_zip(entries)
    with pytest.raises(check.VerificationError):
        fixture.authenticate(blob)


