class Response(io.BytesIO):
    def __init__(self, body, lengths=(), status=200):
        super().__init__(body)
        self.status = status
        self.headers = Message()
        for length in lengths:
            self.headers.add_header("Content-Length", length)


def install_response(monkeypatch, response):
    calls = []
    class Opener:
        def open(self, url, timeout):
            calls.append((url, timeout))
            if isinstance(response, Exception):
                raise response
            return response
    def build(handler):
        assert isinstance(handler, check.NoRedirect)
        return Opener()
    monkeypatch.setattr(check.urllib.request, "build_opener", build)
    return calls


def test_network_request_is_bounded_official_and_single_attempt(monkeypatch):
    calls = install_response(monkeypatch, Response(b"abc", ["3"]))
    assert check.fetch_archive(MODULE, VERSION) == b"abc"
    assert calls == [("https://proxy.golang.org/example.com/!owner/@v/v1.2.3.zip", check.NETWORK_TIMEOUT_SECONDS)]
    calls = install_response(monkeypatch, urllib.error.URLError("offline"))
    with pytest.raises(urllib.error.URLError):
        check.fetch_archive(MODULE, VERSION)
    assert len(calls) == 1


@pytest.mark.parametrize("body,lengths,status", [(b"abc", ["3", "3"], 200), (b"abc", ["-1"], 200), (b"abc", ["three"], 200), (b"abc", ["4"], 200), (b"abc", ["9"], 200), (b"abcdef", [], 200), (b"abc", [], 500)])
def test_network_response_bounds_and_ambiguity(monkeypatch, body, lengths, status):
    monkeypatch.setattr(check, "MAX_ARCHIVE_BYTES", 5)
    calls = install_response(monkeypatch, Response(body, lengths, status))
    with pytest.raises(check.VerificationError):
        check.fetch_archive(MODULE, VERSION)
    assert len(calls) == 1


