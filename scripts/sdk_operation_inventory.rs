//! Emit the canonical Torii operation inventory without compiling node dependencies.
//!
//! Invoked by `sdk_operation_inventory.py` with the repository's pinned Rust toolchain.
//! The route catalog uses only `std`; compile its actual descriptors instead of parsing Rust
//! source or duplicating router metadata. Output is tab-separated and sorted by route identity.

#[path = "../crates/iroha_torii_shared/src/route_catalog.rs"]
mod route_catalog;

use route_catalog::{
    ApiSurface, CATALOGED_ROUTES, FeatureGate, RouteCatalog, RouteEffect, RouteTransport,
};
use std::io::{self, Write};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    RouteCatalog::new(CATALOGED_ROUTES)
        .validate()
        .map_err(|errors| format!("invalid canonical route catalog: {errors:?}"))?;
    let mut routes: Vec<_> = CATALOGED_ROUTES.iter().collect();
    routes.sort_by_key(|route| route.stable_route_id());
    let mut out = io::BufWriter::new(io::stdout().lock());
    writeln!(
        out,
        "# Generated by python3 scripts/sdk_operation_inventory.py --write"
    )?;
    writeln!(
        out,
        "route_id\tmethod\tpath\tsurface\tauthentication\tadmission\teffect\ttransport\tfeature_gate\tsdk\topenapi\tmcp\tprivate_no_store"
    )?;
    for route in routes {
        let surface = match route.surface() {
            ApiSurface::Public => "public",
            ApiSurface::Operator => "operator",
            ApiSurface::Diagnostic => "diagnostic",
            ApiSurface::Protocol => "protocol",
        };
        let effect = match route.effect() {
            RouteEffect::ReadOnly => "read",
            RouteEffect::ExpensiveCompute => "compute",
            RouteEffect::Mutation => "mutation",
            RouteEffect::LongLivedStream => "stream",
        };
        let transport = match route.transport() {
            RouteTransport::Http => "http",
            RouteTransport::ServerSentEvents => "sse",
            RouteTransport::WebSocket => "websocket",
        };
        let gate = match route.feature_gate() {
            FeatureGate::Always => "always".to_owned(),
            FeatureGate::Feature(name) => format!("feature({name})"),
            FeatureGate::All(names) => format!("all({})", names.join(",")),
            FeatureGate::Any(names) => format!("any({})", names.join(",")),
        };
        let fields = [
            route.stable_route_id(),
            route.method().as_str(),
            route.path(),
            surface,
            route.authentication().as_str(),
            route.admission().as_str(),
            effect,
            transport,
            &gate,
        ];
        if fields
            .iter()
            .any(|field| field.contains(['\t', '\r', '\n']))
        {
            return Err(format!("invalid inventory field for {}", route.stable_route_id()).into());
        }
        writeln!(
            out,
            "{}\t{}\t{}\t{}\t{}",
            fields.join("\t"),
            route.projections().sdk(),
            route.projections().openapi(),
            route.projections().mcp(),
            route.requires_private_no_store()
        )?;
    }
    out.flush()?;
    Ok(())
}
