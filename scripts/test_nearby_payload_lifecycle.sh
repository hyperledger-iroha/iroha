#!/usr/bin/env bash
# Build Nearby and exercise payload lifecycle and file timestamps without radios.
# Requires macOS, Xcode and Apple Swift 6.4 or newer (swiftbuild engine).
# Usage: scripts/test_nearby_payload_lifecycle.sh [SwiftPM scratch directory]
set -euo pipefail

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  printf '%s\n' 'Usage: scripts/test_nearby_payload_lifecycle.sh [SwiftPM scratch directory]' \
    'Requires macOS, Xcode and Apple Swift 6.4+. Reuses the SDK dependency lock.'
  exit 0
fi

task_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
task_nearby="$task_root/vendor/nearby"
task_scratch="${1:-$(mktemp -d "${TMPDIR:-/tmp}/iroha-nearby-lifecycle.XXXXXX")}"
mkdir -p "$task_scratch"
task_scratch="$(cd "$task_scratch" && pwd)"

# Preserve any existing consumer lock. A lock generated by this test belongs to
# its scratch evidence, not the exact vendored source closure.
task_had_lock=false
if [[ -e "$task_nearby/Package.resolved" ]]; then
  task_had_lock=true
fi
trap 'if [[ "$task_had_lock" == false && -f "$task_nearby/Package.resolved" ]]; then mv "$task_nearby/Package.resolved" "$task_scratch/qualification-Package.resolved"; fi' EXIT

python3 "$task_root/vendor/boringssl-swiftpm/verify_source.py"
python3 "$task_nearby/verify_source.py"
# Match the graph used by the SDK, even if jan-lts advances upstream.
task_sdk_lock="$task_root/IrohaSwift/Package.resolved"
if [[ "$task_had_lock" == false ]]; then
  cp "$task_sdk_lock" "$task_nearby/Package.resolved"
fi
cmp "$task_sdk_lock" "$task_nearby/Package.resolved"
swift build --package-path "$task_nearby" --scratch-path "$task_scratch" \
  --build-system swiftbuild --force-resolved-versions -j 4
cmp "$task_sdk_lock" "$task_nearby/Package.resolved"
task_abseil="$task_scratch/checkouts/abseil-cpp-SwiftPM"
task_revision="$(python3 -c 'import json, sys; print(next(p["state"]["revision"] for p in json.load(open(sys.argv[1]))["pins"] if p["identity"] == "abseil-cpp-swiftpm"))' "$task_sdk_lock")"
[[ "$(git -C "$task_abseil" rev-parse HEAD)" == "$task_revision" ]]
[[ -z "$(git -C "$task_abseil" status --porcelain --untracked-files=all)" ]]

task_products="$task_scratch/out/Products/Debug"
if [[ ! -f "$task_products/libNearbyConnectionsDynamic.dylib" ]]; then
  printf '%s\n' "Expected macOS SwiftPM dynamic product is absent: $task_products" >&2
  exit 1
fi
for task_fixture in nearby_payload_lifecycle nearby_payload_timestamps; do
  xcrun clang++ -std=c++20 -DNO_WEBRTC -DGITHUB_BUILD -UNDEBUG \
    "$task_root/scripts/tests/fixtures/$task_fixture.cc" \
    -I"$task_nearby" -I"$task_nearby/compiled_proto" \
    -I"$task_nearby/third_party/ukey2/include" \
    -I"$task_nearby/third_party/ukey2/ukey2" \
    -I"$task_nearby/third_party/ukey2/compiled_proto/src/main/proto" \
    -I"$task_nearby/third_party/protobuf/src" \
    -I"$task_nearby/third_party/protobuf/third_party/utf8_range" \
    -I"$task_nearby/third_party/json/json/include" \
    -I"$task_scratch/checkouts/abseil-cpp-SwiftPM" \
    -I"$task_root/vendor/boringssl-swiftpm/include" \
    -L"$task_products" -lNearbyConnectionsDynamic \
    -Wl,-rpath,"$task_products" -o "$task_scratch/$task_fixture"
  "$task_scratch/$task_fixture"
done
python3 "$task_root/vendor/boringssl-swiftpm/verify_source.py"
# Move only the lock this invocation created before checking the source closure.
if [[ "$task_had_lock" == false && -f "$task_nearby/Package.resolved" ]]; then
  mv "$task_nearby/Package.resolved" "$task_scratch/qualification-Package.resolved"
fi
python3 "$task_nearby/verify_source.py"
printf 'Qualification scratch: %s\n' "$task_scratch"
