/// Four pinned BLS-normal members in canonical (ascending peer) order, each with its actual
/// proof of possession.
fn committee() -> Vec<SumeragiLaneMember> {
    let mut members = (41_u8..45)
        .map(|seed| {
            let pair = KeyPair::from_seed(vec![seed; 32], Algorithm::BlsNormal);
            SumeragiLaneMember {
                peer: PeerId::new(pair.public_key().clone()),
                pop: bls_normal_pop_prove(pair.private_key()).expect("BLS-normal lane member PoP"),
            }
        })
        .collect::<Vec<_>>();
    members.sort();
    members
}

