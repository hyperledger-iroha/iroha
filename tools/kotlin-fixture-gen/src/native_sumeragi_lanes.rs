//! Exact `GET /v1/sumeragi/lanes` JSON and canonical framed Norito vectors for SDK parity.
//!
//! Every row is one complete response body: the ordered lane list the node serves
//! (`specs/sumeragi_lanes.md` §8). SDKs parse the JSON column; the Norito column is the
//! `application/x-norito` body of the same response.
