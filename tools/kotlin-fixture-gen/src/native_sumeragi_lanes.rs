/// Render one fixture row: the exact response body is the owned `Vec` the handler serves.
fn row(name: &str, lanes: &[SumeragiLaneStatus]) -> String {
    let lanes = lanes.to_vec();
    let json = norito::json::to_json(&lanes).expect("native lanes JSON");
    let wire = norito::encode_canonical(&lanes).expect("native lanes canonical frame");
    let decoded: Vec<SumeragiLaneStatus> =
        norito::decode_canonical(&wire).expect("Rust exact frame roundtrip");
    assert_eq!(decoded, lanes);
    let decoded_json: Vec<SumeragiLaneStatus> =
        norito::json::from_str(&json).expect("Rust JSON roundtrip");
    assert_eq!(decoded_json, lanes);
    format!("{name}\t{json}\t{}", hex::encode(wire))
}

#[cfg(test)]
mod tests {
    use super::{HEADER, rows};

    const COMMITTED: &str = include_str!("../../../fixtures/sumeragi/native_lanes_v1.tsv");

    #[test]
    fn committed_lane_fixture_matches_current_rust_records() {
        let mut lines = COMMITTED.lines();
        assert_eq!(lines.next(), Some(HEADER), "fixture header changed");
        let committed = lines.map(str::to_owned).collect::<Vec<_>>();
        assert_eq!(
            committed,
            rows(),
            "fixtures/sumeragi/native_lanes_v1.tsv drifted from the Rust lane status DTO; \
             regenerate it with `cargo run -p kotlin-fixture-gen --features dev-tools -- \
             native-sumeragi-lanes-v1 > fixtures/sumeragi/native_lanes_v1.tsv`"
        );
    }
}
