/// Header line of `fixtures/sumeragi/native_lanes_v1.tsv`.
pub const HEADER: &str =
    "# Generated by kotlin-fixture-gen native-sumeragi-lanes-v1; name\tjson\tcanonical_norito_hex";

/// Print the fixture file.
pub fn emit() {
    println!("{HEADER}");
    for line in rows() {
        println!("{line}");
    }
}

