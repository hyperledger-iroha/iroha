final class NativeFiCheckpointAdvanceV1Tests: XCTestCase {
    func testMalformedAndOverBoundPagesRefuseBeforeNativeDispatch() throws {
        let checkpoint = Data([1]), sha = Data(repeating: 2, count: 32), context = Data(repeating: 3, count: 32)
        for page in [[], [Data([1])], [Data(), Data([1])],
                     Array(repeating: Data([1]), count: 4097),
                     [Data(repeating: 1, count: 16 * 1024 * 1024), Data([1])]] {
            XCTAssertThrowsError(try NativeFiCheckpointAdvanceV1.validate(checkpoint: checkpoint,
                proofOriginals: page, chain: "chain", sha: sha, height: 2, context: context))
        }
        for height in [UInt64(0), UInt64.max] {
            XCTAssertThrowsError(try NativeFiCheckpointAdvanceV1.validate(checkpoint: checkpoint,
                proofOriginals: [Data([1]), Data([2])], chain: "chain", sha: sha, height: height, context: context))
        }
        try NativeFiCheckpointAdvanceV1.validate(checkpoint: checkpoint,
            proofOriginals: [Data([1]), Data([2])], chain: "chain", sha: sha, height: 2, context: context)
    }

    func testNativeMetadataChecksDigestDomainSuccessorAndFullUnsignedHeight() throws {
        let checkpoint = Data([4, 5, 6]), height = UInt64.max - 1
        let object: [String: String] = ["schema": "iroha.fi-checkpoint-advance.verified.v1",
            "networkId": "network", "chainId": "chain", "anchorHeight": String(height - 1),
            "height": String(height), "proofCount": "2",
            "checkpointSha256": SHA256.hash(data: checkpoint).map { String(format: "%02x", $0) }.joined(),
            "contextId": String(repeating: "03", count: 32), "blockHash": String(repeating: "05", count: 32)]
        func decode(_ value: [String: String], _ cp: Data = checkpoint) throws -> VerifiedFiCheckpointAdvanceV1 {
            try NativeFiCheckpointAdvanceV1.decodeNativeResult(JSONSerialization.data(withJSONObject: value),
                checkpoint: cp, network: "network", chain: "chain", anchorHeight: height - 1, proofCount: 2)
        }
        let verified = try decode(object)
        XCTAssertEqual(verified.height, height); XCTAssertEqual(verified.checkpoint, checkpoint)
        XCTAssertThrowsError(try decode(object, Data([4, 5, 7])))
        for (key, value) in [("networkId", "other"), ("chainId", "other"), ("anchorHeight", "2"),
                             ("height", String(height - 1)), ("height", "0" + String(height)),
                             ("height", String(UInt64.max)), ("proofCount", "3"),
                             ("contextId", String(repeating: "00", count: 32)),
                             ("blockHash", String(repeating: "04", count: 32)), ("extra", "field")] {
            var changed = object; changed[key] = value
            XCTAssertThrowsError(try decode(changed), key)
        }
    }
}

// Ordinary suite discovery skips only when all four input keys are absent.
// Any selected input requires the complete valid selection and independent fixture/source/artifact
// admission. Missing native support is a failure; the dedicated runner requires one pass, zero skips.
// Receipt assertions are pinned reviewed evidence, not proof generated by this JSON reader.
// Matching the actually loaded native artifact to that reviewed source remains an external gate.
// Immediately before this run, the independently pinned native_c_driver.py --admit-only
// must admit these same four inputs (including duplicate-key and owner-controlled-root checks).
private enum TimeIronwoodPublicCorpusV1 {
    enum Refusal: Error { case invalid(String) }
    struct Original: Equatable { let name: String; let size: Int; let sha256: String }
    struct Corpus {
        let checkpoint: Data; let promoted: Data; let proofs: [Data]
        let network: NetworkId; let chain: String; let anchor: UInt64; let final: UInt64
        let context: Data; let finalContext: Data
    }
    static func need(_ condition: Bool, _ message: String) throws {
        if !condition { throw Refusal.invalid(message) }
    }
    static func object(_ value: Any?, fields: Set<String>) throws -> [String: Any] {
        guard let result = value as? [String: Any], Set(result.keys) == fields else { throw Refusal.invalid("closed JSON fields") }
        return result
    }
    static func text(_ value: Any?) throws -> String {
        guard let result = value as? String else { throw Refusal.invalid("text required") }
        return result
    }
    static func hex(_ value: Any?, width: Int = 64) throws -> String {
        let result = try text(value)
        try need(result.utf8.count == width && result.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
            && result.contains(where: { $0 != "0" }), "nonzero lowercase hex required")
        return result
    }
    static func integer(_ value: Any?) throws -> Int {
        guard let number = value as? NSNumber,
              CFGetTypeID(number) != CFBooleanGetTypeID(),
              !["f", "d"].contains(String(cString: number.objCType)),
              let result = Int(number.stringValue), String(result) == number.stringValue else {
            throw Refusal.invalid("exact JSON integer required")
        }
        return result
    }
    static func boolean(_ value: Any?, equals expected: Bool) throws {
        guard let number = value as? NSNumber, CFGetTypeID(number) == CFBooleanGetTypeID(), number.boolValue == expected else {
            throw Refusal.invalid("exact JSON boolean required")
        }
    }
    static func positiveDecimal(_ value: Any?) throws -> UInt64 {
        let value = try text(value)
        guard let result = UInt64(value), result > 0, String(result) == value else { throw Refusal.invalid("canonical positive decimal required") }
        return result
    }
    static func digest(_ bytes: Data) -> String { SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined() }
    static func path(_ raw: String) throws -> URL {
        let url = URL(fileURLWithPath: raw)
        try need(raw.hasPrefix("/") && url.standardizedFileURL.path == raw && url.resolvingSymlinksInPath().path == raw,
                 "absolute canonical path without symlinks required")
        return url
    }
    static func within(_ url: URL, _ parent: URL) -> Bool { url.path == parent.path || url.path.hasPrefix(parent.path + "/") }
    static func read(_ url: URL, maximum: Int) throws -> Data {
        _ = try path(url.path)
        let attributes = try FileManager.default.attributesOfItem(atPath: url.path)
        try need(attributes[.type] as? FileAttributeType == .typeRegular, "regular original file required")
        let size = try integer(attributes[.size])
        try need(size > 0 && size <= maximum, "file exceeds fixed byte bound")
        let bytes = try Data(contentsOf: url)
        try need(bytes.count == size, "file changed during read")
        return bytes
    }
    static let inputKeys = ["BOI_ACTIVATION_FIXTURE_DIR", "BOI_ACTIVATION_MANIFEST_SHA256",
        "BOI_ACTIVATION_PRODUCER_RECEIPT", "BOI_ACTIVATION_PRODUCER_RECEIPT_SHA256"]
    // Selection is pure: it does not read files or touch the native bridge.
    static func selection(_ environment: [String: String]) throws -> [String: String] {
        let present = inputKeys.filter { environment[$0] != nil }
        try need(present.count == inputKeys.count, "all four BOI_ACTIVATION inputs are required")
        var selected = [String: String]()
        for key in inputKeys {
            guard let value = environment[key], !value.isEmpty else { throw Refusal.invalid("empty " + key) }
            selected[key] = value
        }
        for key in ["BOI_ACTIVATION_MANIFEST_SHA256", "BOI_ACTIVATION_PRODUCER_RECEIPT_SHA256"] { _ = try hex(selected[key]) }
        for key in ["BOI_ACTIVATION_FIXTURE_DIR", "BOI_ACTIVATION_PRODUCER_RECEIPT"] {
            let raw = selected[key]!
            try need(raw.hasPrefix("/") && !raw.utf8.contains(0)
                && URL(fileURLWithPath: raw).standardizedFileURL.path == raw, "absolute normalized activation path required")
        }
        return selected
    }
    static func load(_ environment: [String: String]) throws -> Corpus {
        func required(_ name: String) throws -> String {
            guard let value = environment[name], !value.isEmpty else { throw Refusal.invalid("missing " + name) }
            return value
        }
        let root = try path(required("BOI_ACTIVATION_FIXTURE_DIR"))
        let receiptPath = try path(required("BOI_ACTIVATION_PRODUCER_RECEIPT"))
        let manifestHash = try hex(required("BOI_ACTIVATION_MANIFEST_SHA256"))
        let receiptHash = try hex(required("BOI_ACTIVATION_PRODUCER_RECEIPT_SHA256"))
        var repo = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
        while repo.path != "/" && !FileManager.default.fileExists(atPath: repo.appendingPathComponent("IrohaSwift/Package.swift").path) {
            repo.deleteLastPathComponent()
        }
        try need(repo.path != "/", "cannot establish consumer source root")
        repo = repo.resolvingSymlinksInPath()
        try need(!within(root, repo) && !within(receiptPath, repo) && !within(receiptPath, root), "fixtures and receipt must be external to source; receipt outside corpus")
        let manifestBytes = try read(root.appendingPathComponent("manifest.json"), maximum: 65536)
        let receiptBytes = try read(receiptPath, maximum: 65536)
        try need(digest(manifestBytes) == manifestHash && digest(receiptBytes) == receiptHash, "independently selected public pin differs")
        let manifest = try object(JSONSerialization.jsonObject(with: manifestBytes), fields: [
            "schema", "fixtureKind", "patchBaseCommit", "patchBaseCommitIsProducerSource", "consumerAdmission",
            "networkId", "chainId", "anchorHeight", "finalHeight", "scheduleHeight", "activationHeight", "bootstrapHeight",
            "anchorContextId", "finalContextId", "predecessorSelection", "successorSelection",
            "checkpoint", "promotedCheckpoint", "world", "proofs"])
        try need(text(manifest["schema"]) == "iroha.time-ironwood-native-consumer-fixture.v1"
            && text(manifest["fixtureKind"]) == "certified-synthetic-activation-history"
            && text(manifest["consumerAdmission"]) == "requires-external-producer-receipt", "fixture purpose differs")
        try boolean(manifest["patchBaseCommitIsProducerSource"], equals: false)
        _ = try hex(manifest["patchBaseCommit"], width: 40) // Never compared to the actual producer source.
        _ = try hex(manifest["predecessorSelection"]); _ = try hex(manifest["successorSelection"])
        let anchor = try positiveDecimal(manifest["anchorHeight"]), final = try positiveDecimal(manifest["finalHeight"])
        let schedule = try positiveDecimal(manifest["scheduleHeight"]), activation = try positiveDecimal(manifest["activationHeight"])
        let bootstrap = try positiveDecimal(manifest["bootstrapHeight"])
        try need(anchor < schedule && schedule < activation && activation < bootstrap && bootstrap == final
            && final < UInt64.max && final - activation == 1, "activation history ordering differs")
        let anchorContext = try hex(manifest["anchorContextId"]), finalContext = try hex(manifest["finalContextId"])
        func original(_ value: Any?, expectedName: String) throws -> Original {
            let ref = try object(value, fields: ["name", "size", "sha256"])
            let name = try text(ref["name"])
            let size = try positiveDecimal(ref["size"])
            try need(name == expectedName && !name.contains("/") && !name.contains("\\") && size <= 68 * 1024 * 1024, "original name or size differs")
            return Original(name: name, size: Int(size), sha256: try hex(ref["sha256"]))
        }
        var originals = try [original(manifest["checkpoint"], expectedName: "anchor-checkpoint.norito"),
            original(manifest["promotedCheckpoint"], expectedName: "promoted-checkpoint.norito"),
            original(manifest["world"], expectedName: "world.norito")]
        guard let proofValues = manifest["proofs"] as? [Any] else { throw Refusal.invalid("proof list required") }
        try need((2...4096).contains(proofValues.count) && final - anchor == UInt64(proofValues.count - 1), "proof page count differs")
        for (index, value) in proofValues.enumerated() {
            originals.append(try original(value, expectedName: String(format: "proof-%04d.norito", index)))
        }
        try need(originals[2].size <= 32 * 1024 * 1024 && originals.dropFirst(3).reduce(0, { $0 + $1.size }) <= 16 * 1024 * 1024, "World/page byte bound differs")
        let receipt = try object(JSONSerialization.jsonObject(with: receiptBytes), fields: ["schema", "source", "testExecutable", "buildReceiptSha256", "run", "fixtureManifestSha256", "files"])
        try need(text(receipt["schema"]) == "boi.time-ironwood-fixture-producer.v1" && hex(receipt["fixtureManifestSha256"]) == manifestHash, "producer receipt binding differs")
        let source = try object(receipt["source"], fields: ["commit", "tree", "signedHeadVerified", "cleanBefore", "cleanAfter"])
        _ = try hex(source["commit"], width: 40); _ = try hex(source["tree"], width: 40)
        for flag in ["signedHeadVerified", "cleanBefore", "cleanAfter"] { try boolean(source[flag], equals: true) }
        let executable = try object(receipt["testExecutable"], fields: ["sha256", "size"])
        _ = try hex(executable["sha256"]); try need(integer(executable["size"]) > 0, "test executable size differs")
        _ = try hex(receipt["buildReceiptSha256"])
        let run = try object(receipt["run"], fields: ["testName", "exitCode", "passed", "failed", "ignored"])
        try need(text(run["testName"]) == "runtime::taira_activation::tests::export_time_ironwood_activation_originals_for_native_consumers", "producer test differs")
        for (key, expected) in [("exitCode", 0), ("passed", 1), ("failed", 0), ("ignored", 0)] { try need(integer(run[key]) == expected, "producer run did not pass exactly") }
        guard let receiptFiles = receipt["files"] as? [Any] else { throw Refusal.invalid("producer files required") }
        var admitted = [String: Original]()
        for value in receiptFiles {
            let ref = try object(value, fields: ["name", "size", "sha256"])
            let name = try text(ref["name"]), size = try integer(ref["size"])
            try need(size > 0 && admitted[name] == nil, "duplicate/invalid producer original")
            admitted[name] = Original(name: name, size: size, sha256: try hex(ref["sha256"]))
        }
        try need(admitted == Dictionary(uniqueKeysWithValues: originals.map { ($0.name, $0) }), "producer original set differs")
        let contents = try FileManager.default.contentsOfDirectory(atPath: root.path)
        try need(Set(contents) == Set(originals.map(\.name) + ["manifest.json"]), "unexpected corpus contents")
        var held = [String: Data]()
        for ref in originals {
            let bytes = try read(root.appendingPathComponent(ref.name), maximum: 68 * 1024 * 1024)
            try need(bytes.count == ref.size && digest(bytes) == ref.sha256, "original bytes differ")
            // The hash binds the World original to the reviewed fixture.
            if ref.name != "world.norito" { held[ref.name] = bytes }
        }
        let chain = try text(manifest["chainId"])
        try need(!chain.isEmpty && chain.utf8.count <= 1024, "chain bound differs")
        return Corpus(checkpoint: held[originals[0].name]!, promoted: held[originals[1].name]!,
            proofs: originals.dropFirst(3).map { held[$0.name]! }, network: try NetworkId(literal: text(manifest["networkId"])),
            chain: chain, anchor: anchor, final: final, context: Data(hexString: anchorContext)!, finalContext: Data(hexString: finalContext)!)
    }
}

final class NativeTimeIronwoodActivationV1Tests: XCTestCase {
    func testPinnedExternalActivationCallsRealNativeAdvanceAndRefusesSubstitutions() throws {
        let selected = try TimeIronwoodPublicCorpusV1.selection(ProcessInfo.processInfo.environment)
        let fixture = try TimeIronwoodPublicCorpusV1.load(selected)
        let digest = Data(SHA256.hash(data: fixture.checkpoint))
        func advance(_ frames: [Data], checkpoint: Data = fixture.checkpoint, network: NetworkId = fixture.network,
                     chain: String = fixture.chain, sha: Data = digest, height: UInt64 = fixture.anchor,
                     context: Data = fixture.context) throws -> VerifiedFiCheckpointAdvanceV1 {
            try NativeFiCheckpointAdvanceV1.advance(checkpoint: checkpoint, proofOriginals: frames,
                networkId: network, expectedChain: chain, expectedSHA256: sha, expectedHeight: height, expectedContextID: context)
        }
        let result = try advance(fixture.proofs) // Actual shipping C bridge, no injected positive verifier.
        XCTAssertEqual(result.checkpoint, fixture.promoted)
        XCTAssertEqual(result.checkpointSHA256, Data(SHA256.hash(data: fixture.promoted)))
        XCTAssertEqual(result.anchorHeight, fixture.anchor); XCTAssertEqual(result.height, fixture.final)
        XCTAssertEqual(result.contextID, fixture.finalContext); XCTAssertEqual(result.proofCount, fixture.proofs.count)
        var mutated = fixture.proofs; mutated[mutated.count - 1][0] ^= 1
        XCTAssertThrowsError(try advance(mutated))
        var truncated = fixture.proofs; truncated[truncated.count - 1].removeLast()
        XCTAssertThrowsError(try advance(truncated))
        XCTAssertThrowsError(try advance(Array(fixture.proofs.dropFirst())))
        var gap = fixture.proofs; gap.remove(at: 1)
        XCTAssertThrowsError(try advance(gap))
        let foreignNetwork = try NetworkId(bytes: Data(repeating: 0x11, count: 32))
        XCTAssertNotEqual(foreignNetwork, fixture.network)
        XCTAssertThrowsError(try advance(fixture.proofs, network: foreignNetwork))
        XCTAssertThrowsError(try advance(fixture.proofs, chain: fixture.chain + "-foreign"))
        var wrongDigest = digest; wrongDigest[0] ^= 1
        XCTAssertThrowsError(try advance(fixture.proofs, sha: wrongDigest))
        XCTAssertThrowsError(try advance(fixture.proofs, height: fixture.anchor + 1))
        var wrongContext = fixture.context; wrongContext[0] ^= 1
        XCTAssertThrowsError(try advance(fixture.proofs, context: wrongContext))
        XCTAssertThrowsError(try advance([])); XCTAssertThrowsError(try advance([fixture.proofs[0]]))
        XCTAssertThrowsError(try advance(fixture.proofs, checkpoint: Data()))
        XCTAssertThrowsError(try advance(fixture.proofs, height: 0))
        XCTAssertThrowsError(try advance(fixture.proofs, sha: digest.dropLast()))
        XCTAssertThrowsError(try advance(fixture.proofs, context: fixture.context.dropLast()))
    }
}


final class NativeTimeIronwoodActivationSelectionV1Tests: XCTestCase {
    private let valid = ["BOI_ACTIVATION_FIXTURE_DIR": "/activation-selection/corpus",
        "BOI_ACTIVATION_MANIFEST_SHA256": String(repeating: "1", count: 64),
        "BOI_ACTIVATION_PRODUCER_RECEIPT": "/activation-selection/producer.json",
        "BOI_ACTIVATION_PRODUCER_RECEIPT_SHA256": String(repeating: "2", count: 64)]
    func testAllAbsentRefuses() {
        XCTAssertThrowsError(try TimeIronwoodPublicCorpusV1.selection([:]))
        XCTAssertThrowsError(try TimeIronwoodPublicCorpusV1.selection(["UNRELATED": "value"]))
    }
    func testEveryPartialSelectionRefuses() {
        let keys = TimeIronwoodPublicCorpusV1.inputKeys
        for mask in 1..<15 {
            var partial = [String: String]()
            for (index, key) in keys.enumerated() where (mask & (1 << index)) != 0 { partial[key] = valid[key] }
            XCTAssertThrowsError(try TimeIronwoodPublicCorpusV1.selection(partial))
        }
    }
    func testEmptySelectedValuesRefuse() {
        for key in TimeIronwoodPublicCorpusV1.inputKeys {
            var empty = valid; empty[key] = ""
            XCTAssertThrowsError(try TimeIronwoodPublicCorpusV1.selection(empty))
        }
    }
    func testMalformedSelectedValuesRefuse() {
        for key in ["BOI_ACTIVATION_MANIFEST_SHA256", "BOI_ACTIVATION_PRODUCER_RECEIPT_SHA256"] {
            for value in [String(repeating: "0", count: 64), String(repeating: "A", count: 64), "abc", " " + valid[key]!] {
                var malformed = valid; malformed[key] = value
                XCTAssertThrowsError(try TimeIronwoodPublicCorpusV1.selection(malformed))
            }
        }
        for key in ["BOI_ACTIVATION_FIXTURE_DIR", "BOI_ACTIVATION_PRODUCER_RECEIPT"] {
            for value in ["relative/path", "/activation-selection/../corpus", "/activation-selection/\u{0}corpus"] {
                var malformed = valid; malformed[key] = value
                XCTAssertThrowsError(try TimeIronwoodPublicCorpusV1.selection(malformed))
            }
        }
    }
    func testCompleteWellFormedSelectionNeedsNoFiles() throws {
        XCTAssertEqual(try TimeIronwoodPublicCorpusV1.selection(valid), valid)
    }
}
