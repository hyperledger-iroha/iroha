/// Authentication class required by one atomic-private-settlement operation.
public enum AtomicPrivateSettlementAuthV1: String, Sendable, CaseIterable {
    /// Exact sponsor-account canonical request signature.
    case sponsor = "SPONSOR"
    /// Exact validator or auditor identity request signature.
    case roleIdentity = "ROLE_IDENTITY"
    /// Public redacted query with no identity material.
    case `public` = "PUBLIC"
}

/// Closed mutation catalog for atomic private settlement V1.
public enum AtomicPrivateSettlementOperationV1: String, Sendable, CaseIterable {
    case availabilityShare = "AVAILABILITY_SHARE"
    case prepareVote = "PREPARE_VOTE"
    case commitVote = "COMMIT_VOTE"
    case phaseCertificate = "PHASE_CERTIFICATE"
    case legUpload = "LEG_UPLOAD"
    case auditApproval = "AUDIT_APPROVAL"
    case bundleSubmit = "BUNDLE_SUBMIT"

    /// Exact Torii path, with a payload placeholder only for auditor approval.
    public var path: String {
        switch self {
        case .availabilityShare:
            return "/v1/nexus/private-settlements/legs/availability-shares"
        case .prepareVote:
            return "/v1/nexus/private-settlements/phases/prepare-votes"
        case .commitVote:
            return "/v1/nexus/private-settlements/phases/commit-votes"
        case .phaseCertificate:
            return "/v1/nexus/private-settlements/phases/certificates"
        case .legUpload:
            return "/v1/nexus/private-settlements/legs"
        case .auditApproval:
            return "/v1/nexus/private-settlements/legs/{payload_digest}/audit-approvals"
        case .bundleSubmit:
            return "/v1/nexus/private-settlements/bundles"
        }
    }

    /// Exact identity class required by this operation.
    public var auth: AtomicPrivateSettlementAuthV1 {
        self == .auditApproval ? .roleIdentity : .sponsor
    }

    fileprivate var topLevelFields: Set<String> {
        switch self {
        case .availabilityShare: return ["material"]
        case .prepareVote: return ["manifest", "payload_digest"]
        case .commitVote: return ["payload_digest", "barrier"]
        case .phaseCertificate: return ["manifest", "payload_digest", "certificate"]
        case .legUpload:
            return ["manifest", "audit_policy", "committee_authority", "payload"]
        case .auditApproval: return ["approval"]
        case .bundleSubmit: return ["transaction"]
        }
    }

    fileprivate var maximumRequestBytes: Int {
        switch self {
        case .availabilityShare, .legUpload: return 32 * 1024 * 1024
        case .prepareVote, .commitVote, .phaseCertificate, .bundleSubmit:
            return 8 * 1024 * 1024
        case .auditApproval: return 2 * 1024 * 1024
        }
    }
}

/// Failure from the exact-route atomic-private-settlement client.
public enum AtomicPrivateSettlementClientErrorV1: Error, Equatable, LocalizedError, Sendable {
    case invalidIdentifier
    case invalidPreparedRequest
    case operationSubstitution
    case invalidBaseURL
    case forbiddenHeader(String)
    case invalidResponse
    case responseTooLarge
    case responseSubstitution
    case httpStatus(Int, String?)
    case transport

    public var errorDescription: String? {
        switch self {
        case .invalidIdentifier:
            return "Atomic private settlement identifier is not one exact marked 32-byte hash."
        case .invalidPreparedRequest:
            return "Atomic private settlement request is not a bounded strict native-prepared JSON object."
        case .operationSubstitution:
            return "Prepared atomic private settlement request cannot be sent to this operation."
        case .invalidBaseURL:
            return "Atomic private settlement Torii base URL must be an HTTP(S) URL without query or fragment."
        case let .forbiddenHeader(name):
            return "Atomic private settlement header \(name) is generated by the exact-route client."
        case .invalidResponse:
            return "Atomic private settlement response violated its strict redacted JSON contract."
        case .responseTooLarge:
            return "Atomic private settlement response exceeded its route limit."
        case .responseSubstitution:
            return "Atomic private settlement response identifier was substituted."
        case let .httpStatus(code, rejectCode):
            let suffix = rejectCode.map { "; reject_code=\($0)" } ?? ""
            return "Atomic private settlement request failed with HTTP \(code)\(suffix)."
        case .transport:
            return "Atomic private settlement transport failed."
        }
    }
}

/// Immutable 32-byte Iroha hash identity used in settlement paths and response binding.
public struct AtomicPrivateSettlementIdentifierV1: Hashable, Sendable,
    CustomStringConvertible
{
    private let storage: Data

    /// Validate one exact marked 32-byte Iroha hash.
    public init(bytes: Data) throws {
        guard bytes.count == 32, let last = bytes.last, last & 1 == 1 else {
            throw AtomicPrivateSettlementClientErrorV1.invalidIdentifier
        }
        storage = bytes
    }

    /// Parse a raw 64-digit hash or one exact canonical Norito JSON hash literal.
    public init(_ value: String) throws {
        guard value == value.trimmingCharacters(in: .whitespacesAndNewlines), !value.isEmpty else {
            throw AtomicPrivateSettlementClientErrorV1.invalidIdentifier
        }
        if value.utf8.count == 64, value.utf8.allSatisfy(Self.isHex),
           let bytes = Self.decodeHex(value)
        {
            try self.init(bytes: bytes)
            return
        }
        let networkHash: NetworkId
        do {
            networkHash = try NetworkId(literal: value)
        } catch {
            throw AtomicPrivateSettlementClientErrorV1.invalidIdentifier
        }
        try self.init(bytes: networkHash.bytes)
    }

    /// Exact lowercase raw hexadecimal component accepted in Torii paths.
    public var pathComponent: String { storage.map { String(format: "%02x", $0) }.joined() }

    /// Exact canonical Norito JSON hash literal used by response DTOs.
    public var jsonLiteral: String { (try? NetworkId(bytes: storage).literal) ?? "" }

    /// Defensive copy of the exact identity.
    public var bytes: Data { Data(storage) }

    public var description: String { pathComponent }

    private static func isHex(_ byte: UInt8) -> Bool {
        (0x30...0x39).contains(byte) || (0x41...0x46).contains(byte)
            || (0x61...0x66).contains(byte)
    }

    private static func decodeHex(_ value: String) -> Data? {
        let bytes = Array(value.utf8)
        guard bytes.count == 64 else { return nil }
        var output = Data(capacity: 32)
        for index in stride(from: 0, to: bytes.count, by: 2) {
            guard let high = nibble(bytes[index]), let low = nibble(bytes[index + 1]) else {
                return nil
            }
            output.append((high << 4) | low)
        }
        return output
    }

    private static func nibble(_ byte: UInt8) -> UInt8? {
        switch byte {
        case 0x30...0x39: return byte - 0x30
        case 0x41...0x46: return byte - 0x41 + 10
        case 0x61...0x66: return byte - 0x61 + 10
        default: return nil
        }
    }
}

/// Operation-tagged JSON body prepared by the native Rust wallet/coordinator.
public final class AtomicPrivateSettlementPreparedRequestV1: @unchecked Sendable,
    CustomStringConvertible
{
    public let operation: AtomicPrivateSettlementOperationV1
    private let lock = NSLock()
    private var storage: Data?

    /// Validate strict UTF-8 JSON and bind it to exactly one mutation route.
    public init(
        operation: AtomicPrivateSettlementOperationV1,
        nativePreparedJSON: Data
    ) throws {
        guard !nativePreparedJSON.isEmpty,
              nativePreparedJSON.count <= operation.maximumRequestBytes else {
            throw AtomicPrivateSettlementClientErrorV1.invalidPreparedRequest
        }
        do {
            try StrictJSONDuplicateKeyRejector.rejectDuplicateObjectKeys(
                in: nativePreparedJSON,
                requireAllNumbersInteger: true
            )
        } catch {
            throw AtomicPrivateSettlementClientErrorV1.invalidPreparedRequest
        }
        let object: Any
        do {
            object = try JSONSerialization.jsonObject(
                with: nativePreparedJSON,
                options: [.fragmentsAllowed]
            )
        } catch {
            throw AtomicPrivateSettlementClientErrorV1.invalidPreparedRequest
        }
        guard let fields = object as? [String: Any],
              Set(fields.keys) == operation.topLevelFields else {
            throw AtomicPrivateSettlementClientErrorV1.invalidPreparedRequest
        }
        self.operation = operation
        storage = nativePreparedJSON
    }

    /// Obtain one defensive copy for exact request signing and dispatch.
    public func bytes() throws -> Data {
        lock.lock()
        defer { lock.unlock() }
        guard let storage else {
            throw AtomicPrivateSettlementClientErrorV1.invalidPreparedRequest
        }
        return Data(storage)
    }

    /// Erase the SDK-owned body copy. Native witness memory is never stored here.
    public func close() {
        lock.lock()
        defer { lock.unlock() }
        let byteCount = storage?.count ?? 0
        storage?.resetBytes(in: 0..<byteCount)
        storage = nil
    }

    deinit { close() }

    public var description: String {
        "AtomicPrivateSettlementPreparedRequestV1(operation=\(operation.rawValue), body=[REDACTED])"
    }
}

/// Bounded exact JSON response whose inner proof/capsule material remains opaque to Swift.
public final class AtomicPrivateSettlementJSONResponseV1: @unchecked Sendable,
    CustomStringConvertible
{
    public let route: String
    private let lock = NSLock()
    private var storage: Data?

    fileprivate init(route: String, bytes: Data) {
        self.route = route
        storage = bytes
    }

    /// Defensive copy suitable for the native wallet or auditor worker.
