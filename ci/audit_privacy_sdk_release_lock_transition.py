Identity = tuple[str, str, str]


class AuditError(RuntimeError):
    """Raised when release-lock evidence is not admissible."""


@dataclass(frozen=True)
class LockAuthority:
    label: str
    path: Path
    sha256: str
    mode: int
    raw: bytes
    document: Mapping[str, Any]
    packages: Mapping[Identity, Mapping[str, Any]]


def _fail(message: str) -> NoReturn:
    raise AuditError(message)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _canonical_json(value: Any) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=True,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")


def _identity(package: Mapping[str, Any]) -> Identity:
    return (
        str(package.get("name", "")),
        str(package.get("version", "")),
        str(package.get("source", "")),
    )


def _identity_view(identity: Identity) -> list[str]:
    return [identity[0], identity[1], identity[2]]


def _read_sealed_regular_file(path: Path, label: str) -> tuple[bytes, os.stat_result]:
    try:
        before = path.lstat()
    except OSError as error:
        _fail(f"{label} is unavailable: {error}")
    if not stat.S_ISREG(before.st_mode):
        _fail(f"{label} must be a regular file, not a symlink or special file")
    if before.st_nlink != 1:
        _fail(f"{label} must be singly linked")
    mode = stat.S_IMODE(before.st_mode)
    if mode != EXPECTED_MODE:
        _fail(f"{label} mode must be exactly 0644, found {mode:04o}")
    if before.st_size <= 0 or before.st_size > MAX_LOCK_BYTES:
        _fail(f"{label} size is outside the admissible lockfile bounds")

    flags = os.O_RDONLY
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    try:
        descriptor = os.open(path, flags)
    except OSError as error:
        _fail(f"unable to open {label}: {error}")
    try:
        opened = os.fstat(descriptor)
        if not stat.S_ISREG(opened.st_mode) or opened.st_nlink != 1:
            _fail(f"{label} changed identity while it was opened")
        if (opened.st_dev, opened.st_ino) != (before.st_dev, before.st_ino):
            _fail(f"{label} changed identity while it was opened")
        chunks: list[bytes] = []
        size = 0
        while True:
            chunk = os.read(descriptor, 1024 * 1024)
            if not chunk:
                break
            size += len(chunk)
            if size > MAX_LOCK_BYTES:
                _fail(f"{label} exceeded the maximum lockfile size while read")
            chunks.append(chunk)
        after = os.fstat(descriptor)
    finally:
        os.close(descriptor)

    stable_fields = ("st_dev", "st_ino", "st_mode", "st_nlink", "st_size", "st_mtime_ns")
    if any(getattr(opened, field) != getattr(after, field) for field in stable_fields):
        _fail(f"{label} changed while it was read")
    raw = b"".join(chunks)
    if len(raw) != after.st_size:
        _fail(f"{label} size changed while it was read")
    return raw, after


def _parse_dependency(value: str, label: str) -> tuple[str, str | None, str | None]:
    match = DEPENDENCY_RE.fullmatch(value)
    if match is None:
        _fail(f"{label} contains a non-canonical dependency reference: {value!r}")
    return match.group("name"), match.group("version"), match.group("source")


def _validate_document(raw: bytes, label: str) -> tuple[Mapping[str, Any], dict[Identity, Mapping[str, Any]]]:
    if not raw.startswith(LOCK_HEADER):
        _fail(f"{label} does not have the canonical Cargo lock v4 header")
    if b"\r" in raw or b"\x00" in raw:
        _fail(f"{label} must be canonical NUL-free LF-only text")
    if not raw.endswith(b"\n") or raw.endswith(b"\n\n"):
        _fail(f"{label} must end in exactly one LF")
    if any(line.rstrip(b" \t") != line for line in raw.splitlines()):
        _fail(f"{label} contains trailing horizontal whitespace")
    try:
        text = raw.decode("utf-8", errors="strict")
    except UnicodeDecodeError as error:
        _fail(f"{label} is not UTF-8: {error}")
    try:
        document = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        _fail(f"{label} is not valid TOML: {error}")
    if set(document) != {"version", "package"}:
        _fail(f"{label} has unexpected top-level Cargo.lock fields")
    if document.get("version") != 4:
        _fail(f"{label} must use Cargo lock format version 4")
    package_list = document.get("package")
    if not isinstance(package_list, list) or not package_list:
        _fail(f"{label} must contain a non-empty package array")

    packages: dict[Identity, Mapping[str, Any]] = {}
    allowed_keys = {"name", "version", "source", "checksum", "dependencies"}
    for index, package in enumerate(package_list):
        package_label = f"{label} package[{index}]"
        if not isinstance(package, dict):
            _fail(f"{package_label} is not a TOML table")
        if not {"name", "version"}.issubset(package) or not set(package).issubset(allowed_keys):
            _fail(f"{package_label} has missing or unexpected fields")
        if not isinstance(package["name"], str) or not package["name"]:
            _fail(f"{package_label} has an invalid name")
        if not isinstance(package["version"], str) or not package["version"]:
            _fail(f"{package_label} has an invalid version")
        source = package.get("source")
        checksum = package.get("checksum")
        if source is not None and (not isinstance(source, str) or not source):
            _fail(f"{package_label} has an invalid source")
        if checksum is not None and (
            not isinstance(checksum, str) or SHA256_RE.fullmatch(checksum) is None
        ):
            _fail(f"{package_label} has an invalid checksum")
        if source is None and checksum is not None:
            _fail(f"{package_label} is local but carries a registry checksum")
        if isinstance(source, str) and source.startswith("registry+") and checksum is None:
            _fail(f"{package_label} is a registry package without a checksum")

        dependencies = package.get("dependencies", [])
        if not isinstance(dependencies, list) or any(
            not isinstance(dependency, str) for dependency in dependencies
        ):
            _fail(f"{package_label} has an invalid dependency array")
        if dependencies != sorted(dependencies) or len(dependencies) != len(set(dependencies)):
            _fail(f"{package_label} dependencies must be sorted and unique")
        for dependency in dependencies:
            _parse_dependency(dependency, package_label)

        identity = _identity(package)
        if not all(identity[:2]) or identity in packages:
            _fail(f"{label} contains a duplicate or invalid package identity: {identity!r}")
        packages[identity] = package

    by_name: dict[str, list[Identity]] = {}
    for identity in packages:
        by_name.setdefault(identity[0], []).append(identity)
    for identity, package in packages.items():
        for dependency in package.get("dependencies", []):
            name, version, source = _parse_dependency(dependency, f"{label} {identity!r}")
            candidates = by_name.get(name, [])
            if version is not None:
                candidates = [candidate for candidate in candidates if candidate[1] == version]
            if source is not None:
                candidates = [candidate for candidate in candidates if candidate[2] == source]
            if len(candidates) != 1:
                _fail(
                    f"{label} dependency {dependency!r} from {identity!r} resolves to "
                    f"{len(candidates)} package records"
                )
    return document, packages


def load_lock_authority(
    path: Path,
    label: str,
    expected_sha256: str,
) -> LockAuthority:
    """Load and authenticate one exact Cargo.lock authority."""

    raw, metadata = _read_sealed_regular_file(path, label)
    actual_sha256 = _sha256(raw)
    if actual_sha256 != expected_sha256:
        _fail(
            f"{label} SHA-256 mismatch: expected {expected_sha256}, found {actual_sha256}"
        )
    document, packages = _validate_document(raw, label)
    return LockAuthority(
        label=label,
        path=path.resolve(),
        sha256=actual_sha256,
        mode=stat.S_IMODE(metadata.st_mode),
        raw=raw,
        document=document,
        packages=packages,
    )


def _local_records_digest(packages: Mapping[Identity, Mapping[str, Any]]) -> str:
    records = [
        {
            "package": _identity_view(identity),
            "dependencies": list(package.get("dependencies", [])),
        }
        for identity, package in sorted(packages.items())
        if not identity[2]
    ]
    return _sha256(_canonical_json(records))


def audit_transition(v1: LockAuthority, v2: LockAuthority) -> dict[str, Any]:
    """Prove the complete package identity and dependency-list transition."""

    if len(v1.packages) != V1_PACKAGE_COUNT:
        _fail(f"v1 package count changed: expected {V1_PACKAGE_COUNT}, found {len(v1.packages)}")
    if len(v2.packages) != V2_PACKAGE_COUNT:
        _fail(f"v2 package count changed: expected {V2_PACKAGE_COUNT}, found {len(v2.packages)}")

    v1_ids = set(v1.packages)
    v2_ids = set(v2.packages)
    added = frozenset(v2_ids - v1_ids)
    removed = frozenset(v1_ids - v2_ids)
    if added != EXPECTED_ADDED:
        _fail(f"unexpected v1 -> v2 added package identities: {sorted(added)!r}")
    if removed != EXPECTED_REMOVED:
        _fail(f"unexpected v1 -> v2 removed package identities: {sorted(removed)!r}")

    dependency_changes: list[dict[str, Any]] = []
    for identity in sorted(v1_ids & v2_ids):
        old_package = v1.packages[identity]
        new_package = v2.packages[identity]
        old_non_dependencies = {
            key: value for key, value in old_package.items() if key != "dependencies"
        }
        new_non_dependencies = {
            key: value for key, value in new_package.items() if key != "dependencies"
        }
        if old_non_dependencies != new_non_dependencies:
            _fail(f"common package metadata changed outside dependencies: {identity!r}")
        old_dependencies = list(old_package.get("dependencies", []))
        new_dependencies = list(new_package.get("dependencies", []))
        if old_dependencies != new_dependencies:
            dependency_changes.append(
                {
                    "package": _identity_view(identity),
                    "v1": old_dependencies,
                    "v2": new_dependencies,
                }
            )

    dependency_delta_sha256 = _sha256(_canonical_json(dependency_changes))
    if len(dependency_changes) != DEPENDENCY_CHANGE_COUNT:
        _fail(
            "dependency-list change count changed: expected "
            f"{DEPENDENCY_CHANGE_COUNT}, found {len(dependency_changes)}"
        )
    if dependency_delta_sha256 != DEPENDENCY_DELTA_SHA256:
        _fail(
            "dependency-list transition digest changed: expected "
            f"{DEPENDENCY_DELTA_SHA256}, found {dependency_delta_sha256}"
        )

    v1_local_count = sum(1 for identity in v1_ids if not identity[2])
    v2_local_count = sum(1 for identity in v2_ids if not identity[2])
    if v1_local_count != V1_LOCAL_PACKAGE_COUNT or v2_local_count != V2_LOCAL_PACKAGE_COUNT:
        _fail(
            "local package counts changed: expected "
            f"{V1_LOCAL_PACKAGE_COUNT} -> {V2_LOCAL_PACKAGE_COUNT}, found "
            f"{v1_local_count} -> {v2_local_count}"
        )
    local_records_sha256 = _local_records_digest(v2.packages)
    if local_records_sha256 != V2_LOCAL_RECORDS_SHA256:
        _fail(
            "v2 local dependency records changed: expected "
            f"{V2_LOCAL_RECORDS_SHA256}, found {local_records_sha256}"
        )

    # Human-significant compatibility expectations in addition to the complete
    # delta digest above.
    def dependencies(authority: LockAuthority, name: str, version: str) -> set[str]:
        package = authority.packages.get((name, version, ""))
        if package is None:
            _fail(f"{authority.label} lacks required local package {name} {version}")
        return set(package.get("dependencies", []))

    js_v1 = dependencies(v1, "iroha_js_host", "2.0.0-rc.2.0")
    js_v2 = dependencies(v2, "iroha_js_host", "2.0.0-rc.2.0")
    if "iroha_torii_shared" in js_v1 or "iroha_torii_shared" not in js_v2:
        _fail("iroha_js_host does not carry the reviewed iroha_torii_shared transition")

    halo_v1 = dependencies(v1, "iroha_zkp_halo2", "2.0.0-rc.2.0")
    halo_v2 = dependencies(v2, "iroha_zkp_halo2", "2.0.0-rc.2.0")
    if "iroha_crypto" in halo_v1 or "iroha_crypto" not in halo_v2:
        _fail("iroha_zkp_halo2 does not carry the reviewed iroha_crypto transition")
    retired_halo_dependencies = {
        "bellpepper",
        "bellpepper-core",
        "bincode",
        "ff",
        "sha2",
        "vega-prover",
    }
    if not retired_halo_dependencies.issubset(halo_v1) or retired_halo_dependencies & halo_v2:
        _fail("iroha_zkp_halo2 retired dependency closure does not match review")

    python_v1 = dependencies(v1, "iroha_python_rs", "0.0.1")
    python_v2 = dependencies(v2, "iroha_python_rs", "0.0.1")
    if "p256" not in python_v1 or "p256" in python_v2:
        _fail("iroha_python_rs does not carry the reviewed p256 retirement")

    return {
        "added": [_identity_view(identity) for identity in sorted(added)],
        "removed": [_identity_view(identity) for identity in sorted(removed)],
        "dependency_change_count": len(dependency_changes),
        "dependency_delta_sha256": dependency_delta_sha256,
        "dependency_changes": dependency_changes,
        "v1_local_package_count": v1_local_count,
        "v2_local_package_count": v2_local_count,
        "v2_local_records_sha256": local_records_sha256,
    }


def _safe_repository_path(root: Path, relative: str, label: str) -> Path:
    pure = PurePosixPath(relative)
    if pure.is_absolute() or ".." in pure.parts or not pure.parts:
        _fail(f"{label} is not a repository-relative path: {relative!r}")
    candidate = (root / Path(*pure.parts)).resolve()
    try:
        candidate.relative_to(root)
    except ValueError:
        _fail(f"{label} escapes the repository: {relative!r}")
    return candidate


def _load_toml(path: Path, label: str) -> Mapping[str, Any]:
    try:
        metadata = path.lstat()
    except OSError as error:
        _fail(f"{label} is unavailable: {error}")
    if not stat.S_ISREG(metadata.st_mode):
        _fail(f"{label} must be a regular file")
    try:
        return tomllib.loads(path.read_text(encoding="utf-8", errors="strict"))
    except (OSError, UnicodeError, tomllib.TOMLDecodeError) as error:
        _fail(f"{label} is not readable canonical TOML: {error}")


def _manifest_path_for_directory(path: Path) -> Path | None:
    if not path.is_dir():
        return None
    manifest = path / "Cargo.toml"
    if not manifest.is_file() or manifest.is_symlink():
        return None
    return manifest.resolve()


def _workspace_member_manifests(
    root: Path, workspace: Mapping[str, Any]
) -> set[Path]:
    members = workspace.get("members")
    if not isinstance(members, list) or any(not isinstance(item, str) for item in members):
        _fail("workspace.members must be an array of relative glob strings")
    manifests: set[Path] = set()
    for pattern in members:
        pure = PurePosixPath(pattern)
        if pure.is_absolute() or ".." in pure.parts:
            _fail(f"workspace member pattern escapes the repository: {pattern!r}")
        for candidate in root.glob(pattern):
            manifest = _manifest_path_for_directory(candidate)
            if manifest is not None:
                try:
                    manifest.relative_to(root)
                except ValueError:
                    _fail(f"workspace member manifest escapes the repository: {manifest}")
                manifests.add(manifest)

    excludes = workspace.get("exclude", [])
    if not isinstance(excludes, list) or any(not isinstance(item, str) for item in excludes):
        _fail("workspace.exclude must be an array of relative glob strings")
    for pattern in excludes:
        pure = PurePosixPath(pattern)
        if pure.is_absolute() or ".." in pure.parts:
            _fail(f"workspace exclude pattern escapes the repository: {pattern!r}")
        for candidate in root.glob(pattern):
            manifest = _manifest_path_for_directory(candidate)
            if manifest is not None:
                manifests.discard(manifest)
    return manifests


def _patched_path_manifests(root: Path, document: Mapping[str, Any]) -> set[Path]:
    manifests: set[Path] = set()
    patch = document.get("patch", {})
    if not isinstance(patch, dict):
        _fail("workspace patch configuration must be a TOML table")
    for registry, packages in patch.items():
        if not isinstance(packages, dict):
            _fail(f"patch registry {registry!r} must be a TOML table")
        for alias, specification in packages.items():
            if not isinstance(specification, dict) or "path" not in specification:
                continue
            relative = specification["path"]
            if not isinstance(relative, str):
                _fail(f"patched package {alias!r} has a non-string path")
            directory = _safe_repository_path(root, relative, f"patch {alias!r}")
            manifest = _manifest_path_for_directory(directory)
            if manifest is None:
                _fail(f"patched package {alias!r} has no regular Cargo.toml")
            manifests.add(manifest)
    return manifests


def _package_identity_from_manifest(
    document: Mapping[str, Any], workspace_package: Mapping[str, Any], label: str
) -> Identity:
    package = document.get("package")
    if not isinstance(package, dict):
        _fail(f"{label} has no package table")
    name = package.get("name")
    version: Any = package.get("version")
    if isinstance(version, dict) and version.get("workspace") is True:
        version = workspace_package.get("version")
    if not isinstance(name, str) or not name or not isinstance(version, str) or not version:
        _fail(f"{label} has no concrete package name/version")
    return name, version, ""


def _dependency_tables(document: Mapping[str, Any]) -> Iterable[tuple[str, Mapping[str, Any]]]:
    kinds = ("dependencies", "dev-dependencies", "build-dependencies")
    for kind in kinds:
        table = document.get(kind, {})
        if not isinstance(table, dict):
            _fail(f"manifest {kind} must be a TOML table")
        yield kind, table
    target = document.get("target", {})
    if not isinstance(target, dict):
        _fail("manifest target dependencies must be a TOML table")
    for selector, target_table in sorted(target.items()):
        if not isinstance(target_table, dict):
            _fail(f"manifest target {selector!r} must be a TOML table")
        for kind in kinds:
            table = target_table.get(kind, {})
            if not isinstance(table, dict):
                _fail(f"manifest target {selector!r} {kind} must be a TOML table")
            yield f"target.{selector}.{kind}", table


def _resolve_dependency(
    alias: str,
    specification: Any,
    workspace_dependencies: Mapping[str, Any],
) -> tuple[str, bool, Any | None]:
    if isinstance(specification, str):
        return alias, False, None
    if not isinstance(specification, dict):
        _fail(f"dependency {alias!r} has an invalid specification")
    workspace_specification: Any | None = None
    if specification.get("workspace") is True:
        if alias not in workspace_dependencies:
            _fail(f"dependency {alias!r} inherits an unavailable workspace dependency")
        workspace_specification = workspace_dependencies[alias]
        if isinstance(workspace_specification, str):
            package_name = alias
            inherited_optional = False
        elif isinstance(workspace_specification, dict):
            package_name = workspace_specification.get("package", alias)
            inherited_optional = bool(workspace_specification.get("optional", False))
        else:
            _fail(f"workspace dependency {alias!r} has an invalid specification")
        optional = bool(specification.get("optional", inherited_optional))
    else:
        package_name = specification.get("package", alias)
        optional = bool(specification.get("optional", False))
    if not isinstance(package_name, str) or not package_name:
        _fail(f"dependency {alias!r} resolves to an invalid package name")
    return package_name, optional, workspace_specification


def _manifest_dependency_projection(
    root: Path,
    manifests: Mapping[Identity, tuple[Path, Mapping[str, Any], bool]],
    workspace_dependencies: Mapping[str, Any],
) -> tuple[list[dict[str, Any]], str]:
    projection: list[dict[str, Any]] = []
    for identity, (path, document, is_member) in sorted(manifests.items()):
        dependencies: list[dict[str, Any]] = []
        for scope, table in _dependency_tables(document):
            for alias, specification in sorted(table.items()):
                _, _, workspace_specification = _resolve_dependency(
                    alias, specification, workspace_dependencies
                )
                entry: dict[str, Any] = {
                    "scope": scope,
                    "alias": alias,
                    "spec": specification,
                }
                if workspace_specification is not None:
                    entry["workspace_spec"] = workspace_specification
                dependencies.append(entry)
        projection.append(
            {
                "package": _identity_view(identity),
                "path": path.relative_to(root).as_posix(),
                "workspace_member": is_member,
                "dependencies": dependencies,
            }
        )
    digest = _sha256(_canonical_json(projection))
    return projection, digest


def _dependency_base_names(package: Mapping[str, Any]) -> set[str]:
    return {
        _parse_dependency(value, f"package {_identity(package)!r}")[0]
        for value in package.get("dependencies", [])
    }


def audit_workspace(root: Path, v2: LockAuthority) -> dict[str, Any]:
    """Prove v2 local-package parity with the frozen current workspace."""

    root = root.resolve()
    root_manifest_path = root / "Cargo.toml"
    root_document = _load_toml(root_manifest_path, "workspace Cargo.toml")
    workspace = root_document.get("workspace")
    if not isinstance(workspace, dict):
        _fail("workspace Cargo.toml has no workspace table")
    workspace_package = root_document.get("workspace", {}).get("package", {})
    workspace_dependencies = root_document.get("workspace", {}).get("dependencies", {})
    if not isinstance(workspace_package, dict) or not isinstance(workspace_dependencies, dict):
        _fail("workspace package/dependency inheritance tables are unavailable")

    workspace_lock = load_lock_authority(
        root / "Cargo.lock", "tracked workspace Cargo.lock", WORKSPACE_LOCK_SHA256
    )
    if len(workspace_lock.packages) != WORKSPACE_PACKAGE_COUNT:
        _fail(
            "tracked workspace package count changed: expected "
            f"{WORKSPACE_PACKAGE_COUNT}, found {len(workspace_lock.packages)}"
        )

    member_paths = _workspace_member_manifests(root, workspace)
    patched_paths = _patched_path_manifests(root, root_document)
    all_paths = member_paths | patched_paths
    manifest_records: dict[Identity, tuple[Path, Mapping[str, Any], bool]] = {}
    for path in sorted(all_paths):
        document = _load_toml(path, f"local manifest {path.relative_to(root)}")
        identity = _package_identity_from_manifest(
            document, workspace_package, f"local manifest {path.relative_to(root)}"
        )
        if identity in manifest_records:
            _fail(f"duplicate local manifest package identity: {identity!r}")
        manifest_records[identity] = (path, document, path in member_paths)

    local_v2 = {
        identity: package for identity, package in v2.packages.items() if not identity[2]
    }
    local_workspace = {
        identity: package
        for identity, package in workspace_lock.packages.items()
        if not identity[2]
    }
    if len(local_v2) != V2_LOCAL_PACKAGE_COUNT:
        _fail(f"v2 local package count changed: found {len(local_v2)}")
    if len(local_workspace) != WORKSPACE_LOCAL_PACKAGE_COUNT:
        _fail(f"workspace local package count changed: found {len(local_workspace)}")
    if set(manifest_records) != set(local_v2):
        _fail(
            "v2 local package identities do not equal workspace member/patch manifests: "
            f"manifest-only={sorted(set(manifest_records) - set(local_v2))!r}, "
            f"lock-only={sorted(set(local_v2) - set(manifest_records))!r}"
        )
    if set(local_workspace) != set(local_v2):
        _fail("tracked workspace and v2 local package identities diverged")

    member_count = sum(1 for _, _, is_member in manifest_records.values() if is_member)
    patched_nonmember_count = len(manifest_records) - member_count
    if member_count != WORKSPACE_MEMBER_PACKAGE_COUNT:
        _fail(
            f"workspace member package count changed: expected {WORKSPACE_MEMBER_PACKAGE_COUNT}, "
            f"found {member_count}"
        )
    if patched_nonmember_count != PATCHED_NONMEMBER_PACKAGE_COUNT:
        _fail(
            "patched nonmember package count changed: expected "
            f"{PATCHED_NONMEMBER_PACKAGE_COUNT}, found {patched_nonmember_count}"
        )

    projection, projection_sha256 = _manifest_dependency_projection(
        root, manifest_records, workspace_dependencies
    )
    if projection_sha256 != LOCAL_MANIFEST_DEPENDENCY_PROJECTION_SHA256:
        _fail(
            "local manifest dependency projection changed: expected "
            f"{LOCAL_MANIFEST_DEPENDENCY_PROJECTION_SHA256}, found {projection_sha256}"
        )

    for identity, (_, document, is_member) in sorted(manifest_records.items()):
        declared: set[str] = set()
        required: set[str] = set()
        for scope, table in _dependency_tables(document):
            is_dev = scope.endswith("dev-dependencies")
            if is_dev and not is_member:
                continue
            for alias, specification in table.items():
                package_name, optional, _ = _resolve_dependency(
                    alias, specification, workspace_dependencies
                )
                declared.add(package_name)
                if not optional:
                    required.add(package_name)

        v2_dependencies = _dependency_base_names(local_v2[identity])
        workspace_dependencies_for_package = _dependency_base_names(local_workspace[identity])
        if v2_dependencies != workspace_dependencies_for_package:
            _fail(f"v2 and tracked workspace local dependencies diverged for {identity!r}")
        if is_member:
            if v2_dependencies != declared:
                _fail(
                    f"workspace member dependency parity failed for {identity!r}: "
                    f"manifest-only={sorted(declared - v2_dependencies)!r}, "
                    f"lock-only={sorted(v2_dependencies - declared)!r}"
                )
        else:
            if v2_dependencies - declared or required - v2_dependencies:
                _fail(
                    f"patched dependency parity failed for {identity!r}: "
                    f"undeclared-lock={sorted(v2_dependencies - declared)!r}, "
                    f"missing-required={sorted(required - v2_dependencies)!r}"
                )

    return {
        "tracked_lock_sha256": workspace_lock.sha256,
        "tracked_package_count": len(workspace_lock.packages),
        "local_package_count": len(local_workspace),
        "workspace_member_package_count": member_count,
        "patched_nonmember_package_count": patched_nonmember_count,
        "manifest_dependency_projection_sha256": projection_sha256,
        "manifest_dependency_projection_record_count": len(projection),
    }


def run_audit(workspace_root: Path, v1_path: Path, v2_path: Path) -> dict[str, Any]:
    workspace_root = workspace_root.resolve()
    v1 = load_lock_authority(v1_path, "privacy release Cargo.lock v1", V1_SHA256)
    v2 = load_lock_authority(v2_path, "privacy release Cargo.lock v2", V2_SHA256)
    transition = audit_transition(v1, v2)
    workspace = audit_workspace(workspace_root, v2)

    def evidence_path(path: Path) -> str:
        try:
            return path.relative_to(workspace_root).as_posix()
        except ValueError:
            return str(path)

    return {
        "schema": SCHEMA,
        "status": "admissible",
        "v1": {
            "path": evidence_path(v1.path),
            "sha256": v1.sha256,
            "mode": f"{v1.mode:04o}",
            "package_count": len(v1.packages),
        },
        "v2": {
            "path": evidence_path(v2.path),
            "sha256": v2.sha256,
            "mode": f"{v2.mode:04o}",
            "package_count": len(v2.packages),
        },
        "transition": transition,
        "workspace": workspace,
    }


def _parser() -> argparse.ArgumentParser:
    repository_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--workspace-root",
        type=Path,
        default=repository_root,
        help="Iroha workspace root (defaults to the verifier's repository)",
    )
    parser.add_argument(
        "--v1-lock",
        type=Path,
        default=None,
        help="override the v1 authority path",
    )
    parser.add_argument(
        "--v2-lock",
        type=Path,
        default=None,
        help="override the v2 authority path",
    )
    parser.add_argument("--json", action="store_true", help="emit complete canonical JSON evidence")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    arguments = _parser().parse_args(argv)
    root = arguments.workspace_root.resolve()
    v1_path = arguments.v1_lock or root / "ci/privacy_sdk_release_lock_v1.toml"
    v2_path = arguments.v2_lock or root / "ci/privacy_sdk_release_lock_v2.toml"
    try:
        evidence = run_audit(root, v1_path, v2_path)
    except AuditError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if arguments.json:
        print(json.dumps(evidence, ensure_ascii=True, sort_keys=True, separators=(",", ":")))
    else:
        transition = evidence["transition"]
        workspace = evidence["workspace"]
        print(
            "privacy SDK release Cargo.lock transition is admissible: "
            f"{evidence['v1']['sha256']} -> {evidence['v2']['sha256']}; "
            f"packages {evidence['v1']['package_count']} -> {evidence['v2']['package_count']}; "
            f"dependency changes {transition['dependency_change_count']}; "
            f"local manifests {workspace['local_package_count']}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
