    /** The stroke polylines of [glyph] on the 32-unit grid, each `x0, y0, x1, y1, …`. */
    @JvmStatic
    fun strokes(glyph: Int): List<DoubleArray> = STROKES[checkGlyph(glyph)].map { it.copyOf() }

    /** The `8 × 8` area-coverage template (`0..255`, row-major) of [glyph]. */
    @JvmStatic
    fun template(glyph: Int): IntArray =
        TEMPLATES.copyOfRange(checkGlyph(glyph) * TEMPLATE_N * TEMPLATE_N, (glyph + 1) * TEMPLATE_N * TEMPLATE_N)

    /** Returns whether design-grid point `(x, y)` is inked in [glyph]. */
    @JvmStatic
    fun isInked(glyph: Int, x: Double, y: Double): Boolean {
        val radius = STROKE_WIDTH / 2.0
        for (stroke in STROKES[checkGlyph(glyph)]) {
            var point = 0
            while (point + 3 < stroke.size) {
                if (segmentDistance(x, y, stroke[point], stroke[point + 1], stroke[point + 2], stroke[point + 3]) <= radius) {
                    return true
                }
                point += 2
            }
        }
        return false
    }

    /**
     * Derives the matching templates from the stroke definitions.
     *
     * Each of the `8 × 8` cells holds the inked fraction of its `4 × 4` design
     * cells, sampled on a 16×16 grid and scaled to `0..255`.
     */
    @JvmStatic
    fun generateTemplates(): Array<IntArray> {
        val superSamples = 16
        val cell = GLYPH_GRID / TEMPLATE_N.toDouble()
        return Array(GLYPH_COUNT) { glyph ->
            val table = IntArray(TEMPLATE_N * TEMPLATE_N)
            for (v in 0 until TEMPLATE_N) {
                for (u in 0 until TEMPLATE_N) {
                    var inked = 0
                    for (sy in 0 until superSamples) {
                        for (sx in 0 until superSamples) {
                            val x = (u.toDouble() + (sx.toDouble() + 0.5) / superSamples.toDouble()) * cell
                            val y = (v.toDouble() + (sy.toDouble() + 0.5) / superSamples.toDouble()) * cell
                            if (isInked(glyph, x, y)) inked += 1
                        }
                    }
                    val coverage = inked.toDouble() / (superSamples * superSamples).toDouble()
                    table[v * TEMPLATE_N + u] = Math.floor(coverage * 255.0 + 0.5).toInt()
                }
            }
            table
        }
    }

    /** Distance from point `(px, py)` to the segment `(ax, ay)`–`(bx, by)`. */
    private fun segmentDistance(px: Double, py: Double, ax: Double, ay: Double, bx: Double, by: Double): Double {
        val dx = bx - ax
        val dy = by - ay
        val lengthSquared = dx * dx + dy * dy
        val t = if (lengthSquared == 0.0) {
            0.0
        } else {
            (((px - ax) * dx + (py - ay) * dy) / lengthSquared).coerceIn(0.0, 1.0)
        }
        val ex = px - (ax + t * dx)
        val ey = py - (ay + t * dy)
        return Math.sqrt(ex * ex + ey * ey)
    }

    private fun checkGlyph(glyph: Int): Int {
        require(glyph in 0 until GLYPH_COUNT) { "glyph index out of range" }
        return glyph
    }
